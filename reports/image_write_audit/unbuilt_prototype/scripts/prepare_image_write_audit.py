"""Add an independent accepted-write audit to the unchanged readback candidate."""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
NAME='image_write_audit'
OUT=ROOT/'project'/NAME
REPORT=ROOT/'reports'/NAME


def replace_once(text,old,new):
    assert text.count(old)==1, old
    return text.replace(old,new,1)


def main():
    OUT.mkdir(exist_ok=True,parents=True);REPORT.mkdir(exist_ok=True,parents=True)
    base=ROOT/'project/image_readback_diag'
    player=(base/'image_player_readback_diag.v').read_text(encoding='utf-8-sig')
    player=player.replace('module image_player_readback_diag #(','module image_player_write_audit #(')
    player=replace_once(player,'output wire [3:0] diag_verify,','output wire [3:0] diag_write,\n\toutput wire [3:0] diag_verify,')
    player=replace_once(player,'    image_path_probe u_path_probe (','''    wire [3:0] write_audit_status;
    reg [3:0] write_audit_meta, write_audit_sync;
    always @(posedge pix_clk or negedge path_rst_pix) begin
        if(!path_rst_pix) begin write_audit_meta<=0; write_audit_sync<=0; end
        else begin write_audit_meta<=write_audit_status; write_audit_sync<=write_audit_meta; end
    end
    assign diag_write=write_audit_sync;
    image_write_audit #(.WIDTH(WIDTH), .HEIGHT(HEIGHT),
        .RED_X0(WIDTH==640 ? 220 : WIDTH/4), .RED_X1(WIDTH==640 ? 420 : 3*WIDTH/4),
        .RED_Y0(HEIGHT==480 ? 140 : HEIGHT/4), .RED_Y1(HEIGHT==480 ? 340 : 3*HEIGHT/4)) u_write_audit (
        .clk(sdr_clk), .rst_n(path_rst_sdr), .writes_complete(writes_complete),
        .write_valid(app_wr_en && !ref_vld), .write_addr(app_wr_addr),
        .write_data(app_wr_din), .write_dm(app_wr_dm), .status(write_audit_status));
    image_path_probe u_path_probe (''')
    (OUT/'image_player_write_audit.v').write_text('// GENERATED by scripts/prepare_image_write_audit.py\n'+player,encoding='utf-8')
    top=(base/'dmz_eg4s20_readback_diag_top.v').read_text(encoding='utf-8-sig')
    top=top.replace('dmz_eg4s20_readback_diag_top','dmz_eg4s20_write_audit_top')
    top=top.replace('image_player_readback_diag u_player (','wire [3:0] diag_write;\n    image_player_write_audit u_player (')
    top=replace_once(top,'.diag_verify(diag_verify),','.diag_verify(diag_verify), .diag_write(diag_write),')
    top=replace_once(top,'.bin_data(diag_stages[15:12])','.bin_data(diag_write)')
    (OUT/'dmz_eg4s20_write_audit_top.v').write_text('// GENERATED by scripts/prepare_image_write_audit.py\n'+top,encoding='utf-8')
    tb=(base/'tb_image_readback_diag.v').read_text(encoding='utf-8-sig')
    tb=tb.replace('tb_image_readback_diag','tb_image_write_audit')
    tb=tb.replace('    image_player_readback_diag #(','    wire [3:0] diag_write;\n    image_player_write_audit #(')
    tb=replace_once(tb,'.diag_verify(diag_verify),','.diag_verify(diag_verify), .diag_write(diag_write),')
    tb=replace_once(tb,'            check_frame;\n            repeat(8)', '''            chk(diag_write === ((case_index==1 || case_index==2) ? 4'h5 : 4'h1),
                "write audit checks the entire accepted address/data sequence independently");
            check_frame;
            repeat(8)''')
    tb=replace_once(tb,'chk(diag_verify === 4\'h5,"a legitimate white file differs from this diagnostic\'s red-square reference");',
        'chk(diag_verify === 4\'h5,"a legitimate white file differs from this diagnostic\'s red-square reference");\n            chk(diag_write===4\'h5,"white reload resets address audit and reports reference data mismatch");')
    tb=tb.replace('ALL CHECKS PASSED: image_readback_diag','ALL CHECKS PASSED: image_write_audit')
    (OUT/'tb_image_write_audit.v').write_text('// GENERATED by scripts/prepare_image_write_audit.py\n'+tb,encoding='utf-8')
    xml=ET.fromstring((ROOT/'project/image_readback_diag_td.al').read_text(encoding='utf-8-sig').replace('Name="UsedInP&R"','Name="UsedInP&amp;R"'))
    xml.find('Name').text=NAME+'_td'
    for node in xml.findall('./TOP_MODULE/*'):
        if node.tag!='CREATEINDEX':node.text='dmz_eg4s20_write_audit_top'
    for node in xml.findall('.//Source_Files/Verilog/File'):
        if node.attrib['Path']=='image_readback_diag/image_player_readback_diag.v':node.attrib['Path']='image_write_audit/image_player_write_audit.v'
        if node.attrib['Path']=='image_readback_diag/dmz_eg4s20_readback_diag_top.v':node.attrib['Path']='image_write_audit/dmz_eg4s20_write_audit_top.v'
    group=xml.find('.//Source_Files/Verilog')
    info=ET.SubElement(ET.SubElement(group,'File',Path='../rtl/storage/image_write_audit.v'),'FileInfo')
    for key,value in {'UsedInSyn':'true','UsedInP&R':'true','BelongTo':'design_1','CompileOrder':'35'}.items():ET.SubElement(info,'Attr',Name=key,Val=value)
    ET.indent(xml,space='    ')
    ET.ElementTree(xml).write(ROOT/'project/image_write_audit_td.al',encoding='UTF-8',xml_declaration=True)
    inputs=[(ROOT/'project'/node.attrib['Path']).resolve().relative_to(ROOT).as_posix() for node in xml.findall('.//Source_Files//File')]
    inputs+=['scripts/prepare_image_write_audit.py','project/flow_image_write_audit.tcl','project/image_write_audit/tb_image_write_audit.v']
    inputs+=[p.relative_to(ROOT).as_posix() for p in base.glob('*.v')]
    hashes=[{'path':p,'sha256':hashlib.sha256((ROOT/p).read_bytes()).hexdigest().upper()} for p in inputs]
    (REPORT/'build_inputs.json').write_text(json.dumps(hashes,indent=2),encoding='utf-8')
    print(f'Prepared isolated accepted-write audit: {len(hashes)} inputs')


if __name__=='__main__':main()
