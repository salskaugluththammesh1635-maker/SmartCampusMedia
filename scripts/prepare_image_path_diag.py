"""Generate isolated, instrumented copies; never edit the full-image release sources."""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "project/image_path_diag"
REPORT = ROOT / "reports/image_path_diag"


def replace_once(source, old, new):
    if source.count(old) != 1:
        raise ValueError(f"Expected one instrumentation anchor: {old[:90]!r}")
    return source.replace(old, new, 1)


def read(path):
    return (ROOT / path).read_text(encoding="utf-8-sig")


def save(name, source):
    (OUT / name).write_text("// GENERATED by scripts/prepare_image_path_diag.py; edit the generator.\n" + source, encoding="utf-8")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    REPORT.mkdir(parents=True, exist_ok=True)
    player = replace_once(read("rtl/storage/image_player.v"), "module image_player #(", "module image_player_path_diag #(")
    player = replace_once(player, "output wire [2:0] reader_status,", "output wire [15:0] diag_stages,\n\toutput wire [2:0] reader_status,")
    player = replace_once(player, "\nendmodule", """
    image_path_probe u_path_probe (
        .pix_clk(pix_clk), .rst_n_pix(path_rst_pix), .sdr_clk(sdr_clk), .rst_n_sdr(path_rst_sdr),
        .decode_valid(bmp_pixel_valid), .decode_pixel(pixel565),
        .write_valid(app_wr_en && !ref_vld && app_wr_dm == 4'b0000), .write_data(app_wr_din),
        .read_valid(sdr_rd_en), .read_data(sdr_rd_dout),
        .pixel_valid(image_ready && de && pixel_valid), .pixel_data(rgb565), .stages(diag_stages));
endmodule""")
    save("image_player_path_diag.v", player)

    top = replace_once(read("rtl/top/dmz_eg4s20_hdmi_top.v"), "module dmz_eg4s20_hdmi_top #(", "module dmz_eg4s20_image_diag_top #(")
    top = replace_once(top, "    image_player u_player (", "    wire [15:0] diag_stages;\n    image_player_path_diag u_player (")
    top = replace_once(top, ".reader_status(reader_status),", ".reader_status(reader_status), .diag_stages(diag_stages),")
    top = replace_once(top, "    assign led = {sd_fail || image_failed, image_loading, sdram_lock_pix[1], locked,\n                  mode==2, |reader_status[1:0], auto_play, image_ready};", """    // [DEBUG-image-path] No emergency/test-pattern pixels may set the image-red flag.
    reg image_video_red_seen;
    always @(posedge clk_pixel or negedge rst_n) begin
        if (!rst_n) image_video_red_seen <= 0;
        else if (!image_ready) image_video_red_seen <= 0;
        else if (de && image_pixel_valid && mode != 2 && video_rgb == 24'hff0000)
            image_video_red_seen <= 1;
    end
    assign led = {sd_fail || image_failed, |reader_status[1:0], image_video_red_seen,
                  diag_stages[1], diag_stages[5], diag_stages[9], diag_stages[13], image_ready};""")
    for old, new in [
        (".bin_data({1'b0,pattern_sel})", ".bin_data(diag_stages[3:0])"),
        (".bin_data(loader_index[3:0])", ".bin_data(diag_stages[7:4])"),
        (".bin_data(error_value)", ".bin_data(diag_stages[11:8])"),
        (".bin_data(sd_fail ? 4'd1 : (image_failed ? 4'd2 : 4'd0))", ".bin_data(diag_stages[15:12])"),
    ]:
        top = replace_once(top, old, new)
    save("dmz_eg4s20_image_diag_top.v", top)

    tb = replace_once(read("sim/testbench/tb_image_player.v"), "module tb_image_player #(parameter FULL=0);", "module tb_image_path_diag #(parameter FULL=0);")
    tb = replace_once(tb, "    image_player #(", "    wire [15:0] diag_stages;\n    image_player_path_diag #(")
    tb = replace_once(tb, ".reader_status(reader_status),", ".reader_status(reader_status), .diag_stages(diag_stages),")
    tb = replace_once(tb, "    integer checks=0, fails=0, pattern_id=0;", "    integer fault_kind=0;\n    integer checks=0, fails=0, pattern_id=0;")
    tb = replace_once(tb, "golden888 = {gr,gg,gb};", """golden888 = (pattern_id == 0 &&
                gx >= (FULL ? 220 : W/4) && gx < (FULL ? 420 : 3*W/4) &&
                gy >= (FULL ? 140 : H/4) && gy < (FULL ? 340 : 3*H/4)) ? 24'hff0000 : 24'hffffff;""")
    tb = replace_once(tb, "expect565=to565(golden888(x,y));", "expect565=(fault_kind != 0) ? 16'hffff : to565(golden888(x,y));")
    begin = tb.index('    initial begin\n        $display("CASE 1:')
    end = tb.index('    initial begin #500000000;', begin)
    tb = tb[:begin] + """    integer case_index;
    reg [15:0] expected_stages;
    initial begin
        build_bmp(W,H,54,0); build_image(W,H,54,0,4,0);
        repeat(8) @(negedge clk); rst_n=1;
        for (case_index=0; case_index < (FULL ? 1 : 5); case_index=case_index+1) begin
            fault_kind=case_index;
            case(case_index)
                0: expected_stages=16'h7777;
                1: begin force dut.pixel565=16'hffff; expected_stages=16'h1111; end
                2: begin force dut.app_wr_din=32'hffffffff; expected_stages=16'h7111; end
                3: begin force dut.sdr_rd_dout=32'hffffffff; expected_stages=16'h7711; end
                4: begin force dut.rgb565=16'hffff; expected_stages=16'h7771; end
            endcase
            if (case_index != 0) request_image(1);
            terminal; chk(image_ready && !failed,"diagnostic image commits");
            check_frame;
            repeat(8) @(negedge clk);
            $display("PATH_DIAG case=%0d stages=%h expected=%h",case_index,diag_stages,expected_stages);
            chk(diag_stages === expected_stages,"stage flags locate the injected white-data boundary");
            release dut.pixel565;
            release dut.app_wr_din;
            release dut.sdr_rd_dout;
            release dut.rgb565;
        end
        if (!FULL) begin
            // A legitimate white reload must clear every prior red/nonwhite flag.
            fault_kind=0; pattern_id=1;
            build_bmp(W,H,54,0); build_image(W,H,54,0,4,0);
            request_image(1); terminal; check_frame;
            chk(diag_stages === 16'h1111,"white reload clears stale red flags across both domains");
        end
        $display("SUMMARY: checks=%0d errors=%0d",checks,fails);
        if(fails==0) $display("ALL CHECKS PASSED: image_path_diag");
        else $display("CHECKS FAILED: image_path_diag");
        $finish;
    end
""" + tb[end:]
    save("tb_image_path_diag.v", tb)

    # Explicit source list: no dependency on TD's directory auto-discovery.
    verilog = [
        "ip/config/sdram/global_def.v", "ip/local/sdram/sdr_wrrd.enc.v",
        "ip/local/sdram/sdr_init_ref.enc.v", "ip/local/sdram/sdr_as_ram.enc.v",
        "rtl/common/seg_decoder.v", "rtl/display/seg_scan4.v", "rtl/input/key_matrix_4x4.v",
        "rtl/audio/buzzer_tone.v", "rtl/audio/pwm_audio_out.v", "rtl/common/async_fifo.v",
        "rtl/video/video_timing_gen.v", "rtl/video/test_pattern_gen.v", "rtl/video/hdmi/hdmi_pll.v",
        "rtl/storage/sdram_pll.v", "rtl/storage/sdram_ctrl_wrap.v", "rtl/storage/framebuf_arbiter.v",
        "rtl/storage/pix_reader.v", "rtl/storage/sd_spi_ctrl.v", "rtl/storage/sd_probe.v",
        "rtl/storage/fat32_reader.v", "rtl/storage/bmp_parser.v", "rtl/storage/img_loader.v",
        "rtl/control/player_ctrl.v", "rtl/storage/image_path_probe.v",
        "project/image_path_diag/image_player_path_diag.v", "project/image_path_diag/dmz_eg4s20_image_diag_top.v",
    ]
    vhdl = ["rtl/video/hdmi/hdmi_tx.vhd"] + ["ip/local/hdmi/enc/" + name for name in
        ["DVITransmitter.enc.vhd", "SerializerN_1_lvds.enc.vhd", "SerializerN_1_lvds_dat.enc.vhd", "TMDSEncoder.enc.vhd"]]
    adc = "constraints/dmz_eg4s20_hdmi.adc"
    sdc = "constraints/dmz_eg4s20_hdmi.sdc"
    xml = ET.fromstring(read("project/sdram_frame_diag_td.al").replace('Name="UsedInP&R"', 'Name="UsedInP&amp;R"'))
    xml.find("Name").text = "image_path_diag_td"
    for node in xml.findall("./TOP_MODULE/*"):
        if node.tag != "CREATEINDEX": node.text = "dmz_eg4s20_image_diag_top"
    files = xml.find("Source_Files")
    files.clear()
    compile_order = 0
    for kind, paths in [("Verilog", verilog), ("VHDL", vhdl), ("ADC_FILE", [adc]), ("SDC_FILE", [sdc])]:
        group = ET.SubElement(files, kind)
        for path in paths:
            compile_order += 1
            rel = path.removeprefix("project/") if path.startswith("project/") else "../" + path
            info = ET.SubElement(ET.SubElement(group, "File", Path=rel), "FileInfo")
            attrs = {"UsedInSyn": "true", "UsedInP&R": "true", "BelongTo": "constraint_1" if kind.endswith("_FILE") else "design_1", "CompileOrder": str(compile_order)}
            if path.endswith("/global_def.v"): attrs["AutoExcluded"] = "true"
            for key, value in attrs.items(): ET.SubElement(info, "Attr", Name=key, Val=value)
    ET.indent(xml, space="    ")
    ET.ElementTree(xml).write(ROOT / "project/image_path_diag_td.al", encoding="UTF-8", xml_declaration=True)
    inputs = verilog + vhdl + [adc, sdc, "project/flow_image_path_diag.tcl",
        "rtl/storage/image_player.v", "rtl/top/dmz_eg4s20_hdmi_top.v",
        "scripts/prepare_image_path_diag.py", "sim/testbench/tb_image_player.v",
        "project/image_path_diag/tb_image_path_diag.v"]
    hashes = [{"path": p, "sha256": hashlib.sha256((ROOT/p).read_bytes()).hexdigest().upper()} for p in inputs]
    (REPORT / "build_inputs.json").write_text(json.dumps(hashes, indent=2), encoding="utf-8")
    print(f"Prepared isolated image-path diagnostic: {len(hashes)} hashed inputs")


if __name__ == "__main__":
    main()
