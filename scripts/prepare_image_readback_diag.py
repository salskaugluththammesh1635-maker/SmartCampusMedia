"""Isolated full-image continuous readback candidate based on the observed 7711 bit."""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/"project/image_readback_diag"
REPORT=ROOT/"reports/image_readback_diag"


def replace_once(source, old, new):
    if source.count(old)!=1:
        raise ValueError(f"Expected one diagnostic anchor: {old[:90]!r}")
    return source.replace(old,new,1)


def read(path):
    return (ROOT/path).read_text(encoding="utf-8-sig")


def save(name, source):
    (OUT/name).write_text("// GENERATED by scripts/prepare_image_readback_diag.py\n"+source,encoding="utf-8")


def main():
    OUT.mkdir(parents=True,exist_ok=True)
    REPORT.mkdir(parents=True,exist_ok=True)
    base="project/image_path_diag/"
    player=replace_once(read(base+"image_player_path_diag.v"),"module image_player_path_diag #(","module image_player_readback_diag #(")
    player=replace_once(player,"output wire [15:0] diag_stages,","output wire [3:0] diag_verify,\n\toutput wire [15:0] diag_stages,")
    player=replace_once(player,"\twire init_done, ref_vld, arb_error, writes_complete;","""
    wire verify_active, verify_done, verify_mismatch, verify_timeout, verify_red;
    wire verify_rd_en;
    wire [20:0] verify_rd_addr;
    reg [3:0] verify_meta, verify_sync;
    always @(posedge pix_clk or negedge path_rst_pix) begin
        if(!path_rst_pix) begin verify_meta<=0; verify_sync<=0; end
        else begin
            verify_meta<={verify_timeout,verify_mismatch,verify_red,verify_done};
            verify_sync<=verify_meta;
        end
    end
    assign diag_verify=verify_sync;
\twire init_done, ref_vld, arb_error, writes_complete;""")
    player=replace_once(player,"C_COMMIT: if (complete_sync[1]) begin","C_COMMIT: if (complete_sync[1] && verify_sync[0]) begin")
    player=replace_once(player,".sdr_rd_en(sdr_rd_en), .sdr_rd_dout(sdr_rd_dout),\n\t\t.busy()",".sdr_rd_en(sdr_rd_en && !verify_active), .sdr_rd_dout(sdr_rd_dout),\n\t\t.busy()")
    # Change only the memory wrapper's read input, leaving the arbiter and writes intact.
    cut=player.index("\tsdram_ctrl_wrap #(")
    before, memory=player[:cut], player[cut:]
    memory=replace_once(memory,".app_rd_en(app_rd_en), .app_rd_addr(app_rd_addr),",
        ".app_rd_en(verify_active ? verify_rd_en : app_rd_en), .app_rd_addr(verify_active ? verify_rd_addr : app_rd_addr),")
    player=before+memory
    player=replace_once(player,"    image_path_probe u_path_probe (","""
    image_readback_diag #(.WIDTH(WIDTH), .HEIGHT(HEIGHT),
        .RED_X0(WIDTH==640 ? 220 : WIDTH/4), .RED_X1(WIDTH==640 ? 420 : 3*WIDTH/4),
        .RED_Y0(HEIGHT==480 ? 140 : HEIGHT/4), .RED_Y1(HEIGHT==480 ? 340 : 3*HEIGHT/4)) u_verify (
        .clk(sdr_clk), .rst_n(path_rst_sdr), .writes_complete(writes_complete), .ref_vld(ref_vld),
        .active(verify_active), .app_rd_en(verify_rd_en), .app_rd_addr(verify_rd_addr),
        .rd_valid(sdr_rd_en), .rd_data(sdr_rd_dout), .done(verify_done),
        .mismatch(verify_mismatch), .timed_out(verify_timeout), .red_seen(verify_red));
    image_path_probe u_path_probe (""")
    save("image_player_readback_diag.v",player)

    top=read(base+"dmz_eg4s20_image_diag_top.v").replace("dmz_eg4s20_image_diag_top","dmz_eg4s20_readback_diag_top")
    top=replace_once(top,"    image_player_path_diag u_player (","    wire [3:0] diag_verify;\n    image_player_readback_diag u_player (")
    top=replace_once(top,".diag_stages(diag_stages),",".diag_stages(diag_stages), .diag_verify(diag_verify),")
    top=replace_once(top,"assign led = {sd_fail || image_failed, |reader_status[1:0], image_video_red_seen,",
        "assign led = {sd_fail || image_failed || (|reader_status[1:0]), |diag_verify[3:2], image_video_red_seen,")
    save("dmz_eg4s20_readback_diag_top.v",top)

    tb=read(base+"tb_image_path_diag.v").replace("tb_image_path_diag","tb_image_readback_diag")
    tb=replace_once(tb,"    image_player_path_diag #(","    wire [3:0] diag_verify;\n    image_player_readback_diag #(")
    tb=replace_once(tb,".diag_stages(diag_stages),",".diag_stages(diag_stages), .diag_verify(diag_verify),")
    tb=replace_once(tb,'            check_frame;\n            repeat(8)', '''            chk(diag_verify === ((case_index==0 || case_index==4) ? 4'h3 : 4'h5),
                "direct readback compares actual loaded frame before display starts");
            check_frame;
            repeat(8)''')
    tb=replace_once(tb,'"white reload clears stale red flags across both domains");', '''"white reload clears stale red flags across both domains");
            chk(diag_verify === 4'h5,"a legitimate white file differs from this diagnostic's red-square reference");''')
    tb=tb.replace("ALL CHECKS PASSED: image_path_diag","ALL CHECKS PASSED: image_readback_diag")
    save("tb_image_readback_diag.v",tb)

    xml=ET.fromstring(read("project/image_path_diag_td.al").replace('Name="UsedInP&R"','Name="UsedInP&amp;R"'))
    xml.find("Name").text="image_readback_diag_td"
    for node in xml.findall("./TOP_MODULE/*"):
        if node.tag!="CREATEINDEX": node.text="dmz_eg4s20_readback_diag_top"
    for node in xml.findall(".//Source_Files/Verilog/File"):
        if node.attrib["Path"]=="image_path_diag/image_player_path_diag.v": node.attrib["Path"]="image_readback_diag/image_player_readback_diag.v"
        if node.attrib["Path"]=="image_path_diag/dmz_eg4s20_image_diag_top.v": node.attrib["Path"]="image_readback_diag/dmz_eg4s20_readback_diag_top.v"
    group=xml.find(".//Source_Files/Verilog")
    info=ET.SubElement(ET.SubElement(group,"File",Path="../rtl/storage/image_readback_diag.v"),"FileInfo")
    for key,value in {"UsedInSyn":"true","UsedInP&R":"true","BelongTo":"design_1","CompileOrder":"34"}.items(): ET.SubElement(info,"Attr",Name=key,Val=value)
    ET.indent(xml,space="    ")
    ET.ElementTree(xml).write(ROOT/"project/image_readback_diag_td.al",encoding="UTF-8",xml_declaration=True)
    inputs=[(ROOT/"project"/node.attrib["Path"]).resolve().relative_to(ROOT).as_posix() for node in xml.findall(".//Source_Files//File")]
    inputs += [base+name for name in ["image_player_path_diag.v","dmz_eg4s20_image_diag_top.v","tb_image_path_diag.v"]]
    inputs += ["scripts/prepare_image_readback_diag.py","project/flow_image_readback_diag.tcl","project/image_readback_diag/tb_image_readback_diag.v"]
    hashes=[{"path":p,"sha256":hashlib.sha256((ROOT/p).read_bytes()).hexdigest().upper()} for p in inputs]
    (REPORT/"build_inputs.json").write_text(json.dumps(hashes,indent=2),encoding="utf-8")
    print(f"Prepared isolated continuous image readback: {len(hashes)} inputs")


if __name__=="__main__": main()
