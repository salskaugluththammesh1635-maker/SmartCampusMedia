"""Preserve the tested readback project; create a separate read-DQM fix bit."""
from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'project/image_dm_fix'
REPORT=ROOT/'reports/image_dm_fix'


def main():
    OUT.mkdir(parents=True,exist_ok=True); REPORT.mkdir(parents=True,exist_ok=True)
    base=ROOT/'project/image_readback_diag'
    pairs=[('image_player_readback_diag.v','image_player_dm_fix.v'),
        ('dmz_eg4s20_readback_diag_top.v','dmz_eg4s20_dm_fix_top.v'),
        ('tb_image_readback_diag.v','tb_image_dm_fix.v')]
    for old,new in pairs:
        text=(base/old).read_text(encoding='utf-8-sig')
        text=text.replace('image_player_readback_diag','image_player_dm_fix')
        text=text.replace('dmz_eg4s20_readback_diag_top','dmz_eg4s20_dm_fix_top')
        text=text.replace('tb_image_readback_diag','tb_image_dm_fix')
        text=text.replace('ALL CHECKS PASSED: image_readback_diag','ALL CHECKS PASSED: image_dm_fix')
        (OUT/new).write_text('// GENERATED by scripts/prepare_image_dm_fix.py\n'+text,encoding='utf-8')
    xml=ET.fromstring((ROOT/'project/image_readback_diag_td.al').read_text(encoding='utf-8-sig').replace('Name="UsedInP&R"','Name="UsedInP&amp;R"'))
    xml.find('Name').text='image_dm_fix_td'
    for node in xml.findall('./TOP_MODULE/*'):
        if node.tag!='CREATEINDEX':node.text='dmz_eg4s20_dm_fix_top'
    for node in xml.findall('.//Source_Files/Verilog/File'):
        if node.attrib['Path']=='image_readback_diag/image_player_readback_diag.v':node.attrib['Path']='image_dm_fix/image_player_dm_fix.v'
        if node.attrib['Path']=='image_readback_diag/dmz_eg4s20_readback_diag_top.v':node.attrib['Path']='image_dm_fix/dmz_eg4s20_dm_fix_top.v'
    # TD resolves source paths from its process working directory in this flow.
    # Absolute paths also make command-line and GUI builds agree.
    for node in xml.findall('.//Source_Files//File'):
        node.attrib['Path']=(ROOT/'project'/node.attrib['Path']).resolve().as_posix()
    ET.indent(xml,space='    ')
    ET.ElementTree(xml).write(ROOT/'project/image_dm_fix_td.al',encoding='UTF-8',xml_declaration=True)
    inputs=[(ROOT/'project'/node.attrib['Path']).resolve().relative_to(ROOT).as_posix() for node in xml.findall('.//Source_Files//File')]
    inputs+=['scripts/prepare_image_dm_fix.py','project/flow_image_dm_fix.tcl','project/image_dm_fix/tb_image_dm_fix.v']
    inputs+=[p.relative_to(ROOT).as_posix() for p in base.glob('*.v')]
    (REPORT/'build_inputs.json').write_text(json.dumps([
        {'path':p,'sha256':hashlib.sha256((ROOT/p).read_bytes()).hexdigest().upper()} for p in inputs],indent=2),encoding='utf-8')
    print(f'Prepared independent read-DQM fix project: {len(inputs)} inputs')


if __name__=='__main__':main()
