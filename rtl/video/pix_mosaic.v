// 文件名  : pix_mosaic.v
// 所在位置: rtl/video/pix_mosaic.v
// 所属层次: 视频层 / 图像路（Key8 五档分辨率抽样 —— 水平方向）
// 权威依据: docs/plan_v2/ARCH_ADDENDUM_VIDEO_PATH.md §7.2（Key8 作用域）
//           §9.1（端口契约）  reports/plan_v2/T7_MUST_TEST.md V-01 / V-02
// ============================================================================
// 【一】系统功能
//
//   本模块是 Key8（分辨率四档 + 原始档）的**水平方向**执行者。垂直方向由
//   rtl/storage/pix_reader.v 的行映射完成，两者合起来把母带 SCI.RLE
//   （实为单支 640x480）缩成用户选定的 src_w x src_h 显示尺寸。
//
//   输入是一行 640 拍的有效像素流（active_x = 0..639，与 de/valid_in 同拍），
//   输出仍是 640 拍，但只保留其中 src_w 个抽样点、其余拍保持上一个抽样值。
//   于是下游看到的画面"横向被放大"，等效于马赛克块。
//
//   ⚠️ 本模块**不需要行缓存**：水平抽样是"逐拍就地决定取/不取"，只用一个
//      保持寄存器 hold_pixel 即可，这也是本设计体积极小的根本原因。
//
// 【二】为什么不能照抄 ARCH_ADDENDUM_VIDEO_PATH.md :462-469 的伪码
//
//   那份伪码把输出写成时序块里的 `rgb565_out <= take ? rgb565_in : hold;`。
//   非阻塞赋值取的是**本拍更新之前**的 hold，而 take 又是在同一个时钟沿
//   才被判定 —— 结果是输出整体**落后一拍**，在 src_w = 640（Key8 默认档）
//   时表现为：
//
//     · 画面整体左移 1 像素
//     · 右侧补出 1 列上一行的残留像素
//     · 不报错、不黑屏、综合与静态时序全绿
//     · 只有"逐拍比对 rgb565_out 与 rgb565_in"才抓得到
//
//   ⇒ 正确写法是**组合旁路**：rgb565_out 与 rgb565_in 同拍成立（见【三】）。
//      保持寄存器 hold 只在"本拍不抽样"的分支里被更新，作为下一次抽样前
//      的保持值。
//
// 【三】实现与等价性
//
//   累加器语义（Bresenham 的定点变体）：x_acc 表示"当前已累积的、尚未被
//   输出消耗的源列权重"。每拍加上 src_w（源列侧推进），每当 x_acc 达到
//   一个输出列的量程 640 就抽样一次并扣掉 640。
//
//     take        = (行首) || (x_acc >= 640)
//     rgb565_out  = take ? rgb565_in : hold          ← 组合，同拍
//     valid_out   = valid_in                         ← 直通，零延迟
//
//   由此可得第 i 个抽样点落在输出列
//
//     p_i = ceil(i * 640 / src_w)                     i = 0 .. src_w-1
//
//   —— 这正是 tb_pix_mosaic.v 里独立用整数除法实现的参考模型。两侧写法
//   完全不同（寄存器累加 vs 闭式除法），同时通过才能说明抽样位置无误。
//
//   五档取值下（640/576/512/400/320）一行内的抽样次数恰为 640/576/512/
//   400/320 次，即"不同源列数 == src_w"，行内不累积误差。src_w = 640 时
//   每拍都满足 640 >= 640，hold 每拍更新且 take 恒真 ⇒ 恒等旁路，画面
//   零损失（V-01 红线）。
//
//   抽样语义是**隔点抽取**而非"像素重复放大"：
//     src_w = 320 → 输出 in[0],in[0],in[2],in[2],in[4],in[4] ...
//   两者都是自洽语义，本工程采用抽取式（每个源列被完整显示 w/640 的比例，
//   抽样位置由 ceil 公式给出，不偏不倚）。
//
// 【四】复位与行同步
//
//   video_timing_gen 在消隐期把 active_x 恒置 0（active_x <= de ? ... : 0），
//   因此 `active_x == 11'd0` 是一个可靠的行首判定，且消隐期会反复命中它 ——
//   每命中一次就把 x_acc 重新装载为 src_w、hold 锁存当期总线值。消隐期
//   valid_in 恒为 0，被污染的 hold 不会被下游当作有效像素采样，进而在
//   下一行首拍（take 恒真）被覆盖，不会漏到可见画面。
//
//   Key8 连按换档只需改变 src_w，行首重装载机制保证下一行立刻按新档位
//   抽样，无需额外的 cfg_changed 握手端口。
//
//   ⚠️ 应急态（disp_mode == 2'd2）的"强制旁路"由顶层实现：把 src_w 直接
//      给 16'd640 即退化为恒等通路（见 addendum :380）。本模块不引入
//      disp_mode 端口，保持功能单一，也避免与 ratio_map 的钳位逻辑重复。
// ============================================================================

`timescale 1ns / 1ps

module pix_mosaic (
    input  wire        clk,          // 视频像素时钟（与 active_x / rgb565_in 同域）
    input  wire        rst_n,        // 异步复位，低有效
    input  wire [10:0] active_x,     // 有效区内水平坐标 0..639，消隐期为 0
    input  wire [15:0] src_w,        // 目标源宽 {640,576,512,400,320}
    input  wire [15:0] rgb565_in,    // 源像素（本设计只做列抽样，不解释像素内容）
    input  wire        valid_in,     // 像素有效（= de 经 window_mask 门控后的像素有效）
    output wire [15:0] rgb565_out,   // 抽样/保持后的像素，与 rgb565_in 同拍
    output wire        valid_out     // 与 valid_in 同拍直通
);

    // ------------------------------------------------------------------------
    // 参数
    // ------------------------------------------------------------------------
    // 输出域一行有效像素数。固定 640，因为本模块处在"已定标到 640 宽"的
    // 视频域里；Key8 改的是"从母带抽多少个点进来"，不是改输出时序。
    localparam [15:0] OUT_W  = 16'd640;

    // ------------------------------------------------------------------------
    // 内部寄存器
    // ------------------------------------------------------------------------
    reg  [15:0] x_acc;               // 源列权重累加器
    reg  [15:0] hold;                // 保持像素（本模块唯一的像素寄存器）

    // ------------------------------------------------------------------------
    // 抽样判定 + 组合旁路输出
    //
    //   take 为真的拍直接旁路 rgb565_in，因此 rgb565_out 与 rgb565_in 严格
    //   同拍 —— 这是 V-01 红线的实现保证，不要改成时序赋值。
    //
    //   行首（active_x == 0）强制抽样：既保证每行第一拍一定是源列 0，
    //   也给累加器一个确定的、与键盘换档无关的重同步点。
    // ------------------------------------------------------------------------
    wire take = (active_x == 11'd0) || (x_acc >= OUT_W);

    assign rgb565_out = take ? rgb565_in : hold;

    // valid 直通：本模块不引入任何延迟，下游 content_mux 的数值/位置关系
    // 因此与改造前完全一致。复位期间上游 de 已为 0，故此处不再叠加 rst_n
    // 门控（省一个 LUT，且避免多出一条与 de 不同源的使能路径）。
    assign valid_out = valid_in;

    // ------------------------------------------------------------------------
    // 累加器与保持寄存器
    //
    //   功能: 每拍推进 x_acc；跨过量程 640 时抽样并扣减，否则保持上一样本。
    //   输入: active_x / src_w / rgb565_in
    //   输出: x_acc、hold（组合输出见上）
    //   ⚠️为什么: hold 只在"不抽样"的拍里保留旧值，抽样拍必须同步写入
    //      rgb565_in，否则下次保持会把更早的样本无限延长（块宽漂移）。
    // ------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            x_acc <= 16'd0;
            hold  <= 16'd0;
        end
        else if (active_x == 11'd0) begin
            // 行首重同步：不管上一行停在哪个余量，本行从 src_w 重新起算
            x_acc <= src_w;
            hold  <= rgb565_in;
        end
        else if (x_acc >= OUT_W) begin
            // 本拍抽样：扣掉一个输出列的量程，余量留到下一拍累积
            x_acc <= x_acc + src_w - OUT_W;
            hold  <= rgb565_in;
        end
        else begin
            // 本拍不抽样：只推进累加器，hold 保持（不写即为保持）
            x_acc <= x_acc + src_w;
        end
    end

endmodule
