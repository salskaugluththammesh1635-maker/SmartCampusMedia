// ============================================================================
// 文件名  : brightness_apply.v
// 所在位置: rtl/video/brightness_apply.v
// 所属层次: 视频层 / 像素通路亮度级
// 权威依据: captain 裁决 m00290（位置 / 纯组合 / 档位方向，最终定稿）
//           docs/plan_v2/KEYMAP.md §9.1（10 档数值，方向按 m00290 修正）
// ============================================================================
// 【一】系统功能
//   Key6 的 10 档亮度调节，插在像素通路的第 4 级：
//
//     ... → content_mux → video_overlay → 【本模块】→ osd_panel → axis → HDMI
//                              ↑                        ↑
//                        字幕/波形/电平条          参数面板
//
// 【二】为什么亮度必须放在这个位置（赛规 1.4(4) 的直接后果）
//   赛规 1.4(4) 原文要求「按键调节亮度后，参数变化信息可读」。
//
//   亮度在三个候选位置上的后果：
//   ┌─────────────────────────┬────────────────────────────────────────┐
//   │ 位置                    │ 后果                                   │
//   ├─────────────────────────┼────────────────────────────────────────┤
//   │ overlay 内部（改造前）  │ 字幕与画面同模块，调暗时字幕一起变暗。 │
//   │                         │ 最低档时字幕几乎不可读 → 违反 1.4(4)   │
//   │ **overlay 后、osd_panel │ 画面（含字幕）变暗，参数面板不受影响。 │
//   │ 前（v2 采用）**         │ 用户按 Key6 → 画面变暗、面板清晰 → ✅  │
//   │ osd_panel 之后          │ 面板也被调暗 → 同样违反 1.4(4)      ❌ │
//   └─────────────────────────┴────────────────────────────────────────┘
//
//   为什么"字幕被调暗"可以接受：字幕（ticker_en）是**内容**的一部分，
//   随画面一起变暗符合"显示亮度"的直觉；参数面板是**UI 反馈**，承载的是
//   参数数值本身，必须始终可读。这正是 1.4(4) 的立法意图。
//
// 【三】为什么纯组合、零寄存器
//   ARCH.md 早期草案曾在本模块打一拍（寄存 de 与 rgb）。那样做是错的：
//   打拍只延了 de 与 rgb，**没延 active_x/active_y**，下游 osd_panel 靠
//   x/y 定位面板矩形，会在面板边界看到 1 像素错位（面板整体横向偏移）。
//   要么把 x/y/de/rgb 四路一起打拍（+35 REG），要么干脆组合。
//
//   选组合的第二个理由：本工程 hold WNS 仅 +0.003 ns，再加寄存器级只会
//   恶化时序。同级风格参照：image_window_mask.v（43 行纯组合）、
//   fade_mixer.v（纯组合）。三者一致，维护时不需要记"哪个打了拍"。
//
//   第三：本模块组合深度很浅（最多 2 级 8 bit 加减 + 1 级 10 选 1 mux），
//   串在 overlay 之后、osd_panel 之前，25 MHz（40 ns）下绰绰有余。
//
// 【四】10 档数值表（档 0 = 最亮 32/32，档 9 = 最暗 3/32）
//
//   ★ 方向必须与既有硬件一致 ★
//   改造前 video_overlay.v:108 是 `bright_sel == 3'd0 ? r_in`，即 0 = 直通
//   = 最亮。若反序（0=最暗），Key6 的按键方向会与老工程相反，用户升级后
//   会觉得"灯坏了"。所以档位方向锁定为 0→9 单调递减。
//
//   档位 增益   占比    实现（x 为 8 bit 通道值）           x=255 时输出
//   ─────────────────────────────────────────────────────────────────────
//    0   32/32 100.0%  x                                    255
//    1   29/32  90.6%  x - (x>>4) - (x>>5)                  233
//    2   26/32  81.3%  x - (x>>3) - (x>>4)                  209
//    3   23/32  71.9%  x - (x>>2) - (x>>5)                  185
//    4   20/32  62.5%  x - (x>>2) - (x>>3)                  161
//    5   16/32  50.0%  (x>>1)                               127
//    6   13/32  40.6%  (x>>1) - (x>>4) - (x>>5)             105
//    7   10/32  31.3%  (x>>2) + (x>>4)                       78
//    8    6/32  18.8%  (x>>3) + (x>>4)                       46
//    9    3/32   9.4%  (x>>4) + (x>>5)                       22
//
//   误差来源是右移截断，单档最大约 2 LSB（0.8% 满幅）。人眼对 10 档之间
//   **单调性**极敏感、对单档 0.8% 绝对误差不敏感，所以这里优先保证
//   "档位越高越亮、严格单调"，数值精度让位于单调性。上表 x=255 一列
//   即单调性核对（255>233>209>185>161>127>105>78>46>22，严格递减 ✓），
//   并由 sim/testbench/tb_brightness_apply.v 逐档断言。
//
//   全部 10 档只用移位 + 1~2 个 8 bit 加减，**零 DSP、零乘法器**。
//   本工程 DSP 余量仅 10/29（reports/plan_v2/RESOURCE_BUDGET.md），
//   任何一处误用乘法器都会挤掉音频通路。
// ============================================================================
module brightness_apply (
    input  wire        de,              // 数据使能（有效显示区）
    input  wire [23:0] rgb_in,          // 输入像素 RGB888
    input  wire [3:0]  bright_lvl,      // 亮度档 0~9：0=最亮 9=最暗（Key6）
    output wire        de_out,          // 组合直通
    output wire [23:0] rgb_out          // 亮度处理后的像素
);

    wire [7:0] r_in = rgb_in[23:16];
    wire [7:0] g_in = rgb_in[15:8];
    wire [7:0] b_in = rgb_in[7:0];

    // ========================================================================
    // 单通道 10 档衰减
    //
    // 为什么用 9 位中间值：
    //   各档的项绝对值之和 ≤ x（逐档核对：最大是档 1 的 x>>4 + x>>5 ≈ 0.09x，
    //   档 9 的 x>>4+x>>5 同理），所以按数学不会溢出也不会为负。但这是
    //   基于当前这张表的推导 —— 一旦有人调整系数（比如把档 2 改成
    //   x - (x>>1) - (x>>2)），8 位就会静默回绕，亮部突然变黑，是最刺眼
    //   的一类显示缺陷。故在结构上留 1 位余量 + 饱和截断，把"表写错"的
    //   后果从"显示异常"降级为"某档偏亮"，可排查、不致命。
    // ========================================================================
    function [7:0] brt10;
        input [7:0] x;
        input [3:0] lvl;
        reg   [8:0] y;
        begin
            case (lvl)
                4'd0:    y = {1'b0, x};                                            // 32/32
                4'd1:    y = {1'b0, x}        - {2'b00, (x >> 4)} - {3'b000, (x >> 5)};
                4'd2:    y = {1'b0, x}        - {1'b0,  (x >> 3)} - {2'b00, (x >> 4)};
                4'd3:    y = {1'b0, x}        - {1'b0,  (x >> 2)} - {3'b000, (x >> 5)};
                4'd4:    y = {1'b0, x}        - {1'b0,  (x >> 2)} - {1'b0,  (x >> 3)};
                4'd5:    y = {1'b0, (x >> 1)};                                     // 16/32
                4'd6:    y = {1'b0, (x >> 1)} - {2'b00, (x >> 4)} - {3'b000, (x >> 5)};
                4'd7:    y = {1'b0, (x >> 2)} + {1'b0,  (x >> 4)};                 // 10/32
                4'd8:    y = {1'b0, (x >> 3)} + {1'b0,  (x >> 4)};                 //  6/32
                default: y = {1'b0, (x >> 4)} + {2'b00, (x >> 5)};                 //  3/32
            endcase
            // 饱和：越过 255 钉在 255，低于 0 钉在 0（后者理论上不会发生，防御性保留）
            brt10 = y[8] ? 8'hFF : y[7:0];
        end
    endfunction

    // ========================================================================
    // 纯组合输出（与 image_window_mask.v / fade_mixer.v 风格一致）
    //   消隐期输出 0，与上游 video_overlay 的 `de ? rgb : 0` 约定一致，
    //   避免消隐期残留数据被 rgb_to_axis 采到。
    // ========================================================================
    assign de_out  = de;
    assign rgb_out = de ? {brt10(r_in, bright_lvl),
                           brt10(g_in, bright_lvl),
                           brt10(b_in, bright_lvl)} : 24'd0;

endmodule
