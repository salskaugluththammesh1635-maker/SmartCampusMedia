// =============================================================================
// seg_decoder.v — 七段数码管段码译码（低电平点亮）
// =============================================================================
// 【一、在整体系统中的功能】
//   所属层次 : 显示层（显示链路的最末端一级）
//   工程归属 : bringup_td.al 与 hdmi_td.al **两个工程共用** —— 复用范例
//   数据流位置:
//       任意数值源（BCD 计数器 / 图案号 / 模式号 / 键号 …）
//            ↓
//       【本模块】──→ 7 位段码 ──→ seg_scan4（动态扫描）──→ 数码管
//   为什么需要它:
//     数码管的 7 段是 7 根彼此独立的线，要点亮数字 "5" 必须让 a/c/d/f/g 段
//     为低、b/e 段为高。人习惯的是"数字"，硬件需要的是"段码位图" ——
//     本模块就是这两者之间的翻译官（本质是一张真值表）。
//
// 【二、本模块功能】
//   一句话职责: 把 4 位十六进制数（0~F）翻译成 7 段数码管的段码。
//   关键特性:
//     - 纯组合逻辑：无时钟、无状态 —— 输入变，输出立即变
//     - **低电平点亮**（0 = 亮，1 = 灭），此极性经官方段码表交叉验证
//     - 位序约定: seg_data[6:0] = {g, f, e, d, c, b, a}
//
// 【三、接口与内部结构】
//   端口一览:
//     输入  bin_data[3:0] : 待显示数值 0~F
//     输出  seg_data[6:0] : 段码输出 {g,f,e,d,c,b,a}，低电平点亮
//
//   内部逻辑块（共 1 块）:
//     [1] 段码查表              always @(*) + case
//           功能: 16 个 case 分支对应 16 个数字/字母的段码；default 全灭
//           输入: bin_data              输出: seg_data
//
//   【段码极性说明】（本项目专门核实过，极易搞反）
//     低电平点亮 → 数字 "0" 的段码为 7'b100_0000:
//       bit6(g)=1 → g 段灭；bit5..0=0 → f/e/d/c/b/a 全亮 → 显示 "0" ✓
//     若按"高电平点亮"理解则完全不是 0。验证依据: 官方 seg_decoder 段码表
//     （"8"→7'b000_0000 全亮）+ 官方 seg_scan 空位填 7'b111_1111（全灭）。
//
//   与官方副本的差异:
//     ① 修复了工程副本第 14 行末尾的孤立字符 'S'（文件损坏 → TD 报错）
//     ② 组合逻辑改用阻塞赋值（符合本工程编码规范: 组合块仅用 =）
//     ③ 段码数值与官方完全一致（官方例程已验证）
//
// 【四、设计思路与范式】
//   主要范式 : 组合译码（Combinational Decode）—— 本项目最纯粹的"真值表"
//   次要范式 : 无（全项目最简单的模块，逻辑仅 20 行）
//   为什么这样写:
//     段码与数字之间是**一一对应的固定映射**，没有任何时序或状态需求，
//     用组合逻辑实现最直接、资源最省（综合后仅几十个 LUT）。
//     若写成时序逻辑，反而平白引入一拍延迟，且毫无必要。
//   关键写法要点:
//     1) 组合块内**只用阻塞赋值 `=`**（用 `<=` 会与 TD 的严格检查冲突）；
//        早期版本因在同一块内混用 `=` 与 `<=`，被 TD 直接报 ERROR
//     2) **必须写 default 分支** —— 否则当 bin_data 出现未列举值时，综合器
//        会推断出锁存器（latch）来"保持上次输出"，这是经典陷阱。
//        本例 default 给全灭（7'b111_1111），语义安全
//     3) 用 case 而非一长串 if-else: 综合器对 case 的译码优化更好，
//        且可读性更强（一张表格一目了然）
//   范式认读方法: 见 docs/design_patterns.md
// =============================================================================
`timescale 1ns / 1ps

module seg_decoder (
    input  wire [3:0] bin_data,     // 待显示数值 0~F
    output reg  [6:0] seg_data      // 段码 {g,f,e,d,c,b,a}, 低电平点亮
);

    // ===================== 唯一的 always 块: 段码查表 =====================
    // 功能: 16 个 case 分支把 4 位输入译成 7 段码（本质就是一张真值表）
    // 输入: bin_data[3:0]              输出: seg_data[6:0]
    // 说明: ① 纯组合逻辑，块内只用阻塞赋值 =
    //       ② default 分支给"全灭"（7'b111_1111），避免综合器推断出锁存器
    //          （若不写 default，输入出现未列举值时硬件会"保持上次输出"，
    //            这不是我们想要的行为）
    always @(*) begin
        case (bin_data)
            4'h0: seg_data = 7'b100_0000;   // 0
            4'h1: seg_data = 7'b111_1001;   // 1
            4'h2: seg_data = 7'b010_0100;   // 2
            4'h3: seg_data = 7'b011_0000;   // 3
            4'h4: seg_data = 7'b001_1001;   // 4
            4'h5: seg_data = 7'b001_0010;   // 5
            4'h6: seg_data = 7'b000_0010;   // 6
            4'h7: seg_data = 7'b111_1000;   // 7
            4'h8: seg_data = 7'b000_0000;   // 8
            4'h9: seg_data = 7'b001_0000;   // 9
            4'hA: seg_data = 7'b000_1000;   // A
            4'hB: seg_data = 7'b000_0011;   // b
            4'hC: seg_data = 7'b100_0110;   // C
            4'hD: seg_data = 7'b010_0001;   // d
            4'hE: seg_data = 7'b000_0110;   // E
            4'hF: seg_data = 7'b000_1110;   // F
            default: seg_data = 7'b111_1111; // 全灭
        endcase
    end

endmodule
