// ============================================================================
// 文件名  : thermal_guard.v
// 所在位置: rtl/sensor/thermal_guard.v
// 所属层次: 传感器层 / 阈值与迟滞判决层（**与具体传感器无关**）
// 作者    : 智播校园项目组
// 更新时间: 2026-11-01
// ============================================================================
// 【一】系统功能
//   智播校园（SmartCampusMedia）的「应急」模式需要环境温度联动：机箱温度过高
//   时强制切到应急画面、拉响蜂鸣器、并禁止用户静音。本模块负责这条链路的
//   **判决部分** —— 只回答一个问题：
//
//        "现在算不算高温？该不该进入应急联动？"
//
//   它不采样、不换算、不认识 I2C，也不认识 NTC。它只吃「一个温度数值 + 一个
//   有效脉冲」，吐「一个联动使能电平 + 一个跳变脉冲」。
//
// 【二】为什么必须做成传感器无关的一层（赛规合规的硬要求）
//   赛规追问的风险点是「成品模块是否含处理器」（见 reports/plan_v2/
//   SPEC_CONSTRAINTS.md §3.1 的 L1/L2/L3 分类）。本工程准备了两套测温方案：
//
//     A 方案（主选）: AHT20 数字温湿度芯片，I2C 接口，挂在 D1/E1 两个复用球。
//                     链路 = i2c_master → aht20_ctrl → 【本模块】
//     B 方案（备选）: EG4S20 片内 8 通道 SAR ADC（12 bit / 有效 8 bit / 1 MHz，
//                     与用户 IO 复用）+ NTC 10k 热敏电阻 + 两个无源电阻，
//                     **外部零芯片**，从根上消灭"模块里有处理器"的质疑。
//                     链路 = sar_adc → ntc_linearize → 【本模块】
//
//   两套方案的下游（应急画面切换、蜂鸣器、禁静音、OSD 提示）必须完全一样，
//   否则答辩时换方案就要改顶层，风险不可控。所以判决逻辑必须抽出来，
//   且**输入契约只有两根线**：温度数值 + 有效脉冲。
//   换方案时本模块一行不改，只换上游驱动。
//
// 【三】输入输出契约（★ spec-auditor 做 t12 Plan B 时按此契约输出，两边不改代码）
//   temp_centi_c[15:0] : **16 位有符号**定点温度，单位 **0.01 ℃**
//                        25.00 ℃ → 16'sd2500
//                         0.00 ℃ → 16'sd0
//                       -40.00 ℃ → -16'sd4000
//                       +85.00 ℃ →  16'sd8500（AHT20 全量程上限）
//                        为什么用 0.01 ℃ 定点而不是 Q8.8：Q8.8 的 25.00 ℃ 应编码为
//                        25×256 = 6400，而"2500"对应的是 0.01 ℃ 定点 —— 两者混用
//                        会造成 2.56 倍的量纲错误且极难察觉。统一取 0.01 ℃ 定点，
//                        理由：AHT20 原生换算 T = raw/2^20 × 200 - 50，要 0.01 ℃
//                        分辨率就是 T_centi = (raw × 20000) >> 20 - 5000，全整数
//                        运算、无浮点、无除法器；16 位有符号覆盖 -327.68 ~ +327.67 ℃，
//                        对 AHT20 的 -40 ~ +85 ℃ 量程绰绰有余。
//   temp_valid         : **单拍脉冲**。只有本拍 temp_centi_c 才是新的有效值。
//                        本模块只在 temp_valid=1 的拍采样，其余拍保持现态。
//                        为什么不用电平：温度更新周期 ≥1 s，而本模块工作在
//                        25 MHz。若用"电平有效"，同一次采样会被重复判决上千万次，
//                        虽不改变结果但会让 temp_update 脉冲连发，污染下游。
//   oth_en             : 高温联动使能（**电平**，保持型）
//   oth_enter          : 进入高温的单拍脉冲（oth_en 由 0→1 的那一拍）
//   oth_exit           : 退出高温的单拍脉冲（oth_en 由 1→0 的那一拍）
//   temp_alive         : 上游是否在正常供数（见下面【五】）
//
// 【四】迟滞（hysteresis）为什么必须有，阈值怎么取
//   若只用一个阈值 45 ℃，当温度在 44.9/45.1 之间抖动时 oth_en 会反复翻转：
//   应急画面切进切出、蜂鸣器断续、OSD 疯狂刷新。这在现场是"设备坏了"的观感。
//   迟滞的做法是给两个阈值：
//     TH_HIGH = 45.00 ℃：**只有温度 ≥ 它才进入**高温
//     TH_LOW  = 40.00 ℃：**只有温度 ≤ 它才退出**高温
//   两者之间（40.00 ~ 44.99 ℃）是"保持区"，维持进入前的状态。
//   5 ℃ 的带宽是刻意取的：AHT20 自身精度 ±0.3 ℃、机箱内空气对流不均匀，
//   实测同一位置两点温差可达 1~2 ℃，5 ℃ 保证任何合理抖动都不会穿带。
//   两个阈值都是 parameter，t12 的 Plan B（NTC 分压 + 8 bit 有效精度）若
//   分辨率不够，可以在例化处放宽到 TH_HIGH=50/TH_LOW=42，无需改本文件。
//
// 【五】temp_alive：为什么需要一个"上游还活着吗"的信号
//   真实故障场景：AHT20 排线松了 / I2C 从机不应答 / NTC 分压电阻虚焊。
//   此时上游要么一直不给 temp_valid，要么给出的数据是冻结的旧值。
//   两种情况下"温度正常"和"传感器坏了"在数值上无法区分 —— 若直接把
//   最后一次读数当作真值，一次高温之后传感器坏掉会让设备**永远卡在应急模式**，
//   反过来一次正常读数之后坏掉会让设备**在真实高温下无动于衷**。
//   本模块因此维护一个存活计数器：连续 STALE_CYCLES 拍没有 temp_valid
//   就判上游失联，temp_alive 拉低。
//   失联时**保持 oth_en 不变**（不主动进也不主动退）—— 理由：这是最保守的
//   选择，宁可维持现状让现场人员看见 OSD 上的"温度传感器异常"提示并人工处理，
//   也不要因为传感器故障导致设备自己切模式。失联状态本身由 OSD 层显示，
//   那是顶层与 osd_panel 的职责，不是本模块的。
//
// 【六】为什么用"单 always 块 + 全部非阻塞"而不是三段式
//   本模块只有一个状态量（oth_en）和两个脉冲输出，没有"次态译码"可言。
//   强行拆三段式反而要引入 oth_next 这个只有一位的中间量，增加理解成本。
//   作为补偿，判决条件写成独立的 wire（enter_hit / exit_hit），让"什么条件
//   触发跳变"有唯一的定义点，改阈值逻辑时只看那两行。
// ============================================================================
module thermal_guard #(
    // ---- 温度阈值（单位 0.01 ℃，16 位有符号）----
    parameter signed [15:0] TH_HIGH = 16'sd4500,  // 45.00 ℃ 及以上 → 进入高温
    parameter signed [15:0] TH_LOW  = 16'sd4000,  // 40.00 ℃ 及以下 → 退出高温
    // ---- 上游失联判定（单位：clk 拍）----
    //   默认 25_000_000 = 25 MHz 下 1 秒。AHT20 的测量周期由 aht20_ctrl 决定
    //   （默认 1 s 一次），这里留 2 倍余量取 2 秒。
    parameter integer STALE_CYCLES = 50_000_000
) (
    input  wire               clk,            // 25 MHz clk_pixel（与传感器驱动同域）
    input  wire               rst_n,          // 异步复位，低有效
    // —— 上游温度输入（契约见【三】）——
    input  wire signed [15:0] temp_centi_c,   // 温度，单位 0.01 ℃
    input  wire               temp_valid,     // 单拍：本拍 temp_centi_c 有效
    // —— 判决输出 ——
    output reg                oth_en,         // 高温联动使能（电平，保持）
    output reg                oth_enter,      // 进入高温单拍
    output reg                oth_exit,       // 退出高温单拍
    output reg                temp_alive      // 上游供数正常（电平）
);

    // ========================================================================
    // 判决条件（唯一的"什么算触发"定义点）
    //   enter_hit：收到有效温度 **且** 该温度 ≥ TH_HIGH **且** 当前不在高温
    //   exit_hit ：收到有效温度 **且** 该温度 ≤ TH_LOW  **且** 当前已在高温
    //   注意两个条件都带 `temp_valid`：没有新读数就不判决，这样进入保持区
    //   时状态自然冻结，不需要额外的"保持态"编码。
    //   比较用 $signed 包裹：temp_centi_c 是 16 位有符号，TH_HIGH/TH_LOW 也是，
    //   但 Verilog 的比较会按无符号解释 reg/wire 的位模式，负温度（-40 ℃ =
    //   0xF060）按无符号是 61536，会被误判为"极高温度"而直接触发高温。
    //   这是本项目最容易踩的一个坑，因此两处比较都显式加 $signed。
    // ========================================================================
    wire signed [15:0] temp_s = temp_centi_c;

    wire enter_hit = temp_valid && !oth_en && (temp_s >= TH_HIGH);
    wire exit_hit  = temp_valid && oth_en  && (temp_s <= TH_LOW);

    // ========================================================================
    // 存活计数器（见【五】）
    //   收到 temp_valid 就清零；否则一直加，加到 STALE_CYCLES 就判失联。
    //   计数器位宽：STALE_CYCLES 默认 50_000_000 < 2^26，取 26 位。
    //   为了让 parameter 改大时不溢出，这里用 $clog2 算位宽 —— 但个别综合器
    //   对参数表达式里的 $clog2 支持不一致，因此写成固定 32 位（资源代价仅
    //   32 个触发器，且综合器会按实际比较常量自动收缩）。
    // ========================================================================
    reg [31:0] stale_cnt;

    // ========================================================================
    // 唯一时序块
    // ========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            oth_en     <= 1'b0;      // 上电默认"非高温"，正常展示内容
            oth_enter  <= 1'b0;
            oth_exit   <= 1'b0;
            temp_alive <= 1'b0;      // 还没收到过任何读数 → 未确认存活
            stale_cnt  <= 32'd0;
        end else begin
            // ---- 两个跳变脉冲默认回零，只在跳变那一拍置 1 ----
            oth_enter <= 1'b0;
            oth_exit  <= 1'b0;

            // ---- 存活计数器 ----
            if (temp_valid) begin
                stale_cnt  <= 32'd0;
                temp_alive <= 1'b1;
            end else if (stale_cnt < STALE_CYCLES) begin
                stale_cnt  <= stale_cnt + 32'd1;
            end else begin
                // 连续 STALE_CYCLES 拍没有新读数 → 判失联
                //   temp_alive 拉低但 oth_en **保持不变**（理由见【五】）
                temp_alive <= 1'b0;
            end

            // ---- 迟滞判决 ----
            if (enter_hit) begin
                oth_en    <= 1'b1;
                oth_enter <= 1'b1;
            end else if (exit_hit) begin
                oth_en   <= 1'b0;
                oth_exit <= 1'b1;
            end
        end
    end

endmodule
