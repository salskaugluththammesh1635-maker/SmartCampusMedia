// =============================================================================
// fade_mixer — 双缓冲换帧的亮度渐变混合器（纯组合，与 de 同拍）
// =============================================================================
// 换帧走"淡出到黑 -> 全黑时翻帧首 -> 淡入"，所以只需一路读通路：
// 淡出阶段读旧帧、淡入阶段读新帧，混合目标恒为黑，不需要同时取两帧像素。
// 这也是不采用交叉溶解的原因：两路读要两个 reader 与双读口仲裁器，
// 会推翻已经验证过的无缝切换结构，且转场期读带宽翻倍。
//
// level=255 输出与输入逐位相同（gain=256 精确整除），level=0 输出全黑。
// 三个通道各自缩放，绝不把 RGB565 当 16 位整数整体缩放——那会把高位通道
// 压进低位通道（0xFFFF>>8 = 0x00FF，红色被压成蓝色）。
// =============================================================================
`timescale 1ns / 1ps
module fade_mixer (
	input wire [15:0] rgb_in,   // RGB565 源像素
	input wire [7:0] level,     // 0=全黑，255=原样
	output wire [15:0] rgb_out  // 同拍混合结果
);
	// gain = level + 1 让两端都精确：level=255 时 gain=256，右移八位还原原值；
	// level=0 时 gain=1，各通道最多 6 位，右移八位必为 0，不会残留暗色。
	wire [8:0] gain = {1'b0, level} + 9'd1;
	wire [4:0] r_in = rgb_in[15:11];
	wire [5:0] g_in = rgb_in[10:5];
	wire [4:0] b_in = rgb_in[4:0];
	// 位宽按 通道位宽+9 取满，不截断乘积，避免综合器把高位优化成常量。
	wire [13:0] r_mul = r_in * gain;
	wire [14:0] g_mul = g_in * gain;
	wire [13:0] b_mul = b_in * gain;
	assign rgb_out = {r_mul[12:8], g_mul[13:8], b_mul[12:8]};
endmodule
