// ============================================================================
// 模块: vol_apply
// 文件: rtl/audio/vol_apply.v
// 版本: v2.0 (campus-media-v2)
// ----------------------------------------------------------------------------
// 功能
//   10 档数字音量，作用在 48 kHz / 16 bit 的 PCM 样本流上。
//   全部用移位加实现，零乘法器、零 DSP 资源（DSP 余量仅剩 10/29，
//   本模块一个都不能占）。
//
// ★★★ 方向约定：与亮度表恰好相反 ★★★
//   亮度 brightness_apply.v : 档 0 = 最亮(32/32) … 档 9 = 最暗( 3/32)
//   音量 vol_apply.v        : 档 0 = 最轻( 3/32) … 档 9 = 最响(32/32)
//   两张表的增益集合完全相同 {3,6,10,13,16,20,23,26,29,32}/32，
//   只是排列顺序相反。这是本工程最容易复制粘贴出错的地方，
//   所以 tb_gain_direction.v 把两个模块放在同一份 tb 里，
//   相邻两行断言各自的方向，任何一次抄错都会立刻挂红。
//   依据：docs/plan_v2/KEYMAP.md §9.2「0 = 最轻（9.4%），9 = 最响（100%）」
//
// ★ 与任务书验收项「音量 0 档仿真输出严格为 0」的差异说明
//   任务书原文写的是「0 = 严格静音」，但 docs/plan_v2/KEYMAP.md §9.2 与
//   captain 裁决 m00903 都定死「档 0 = 3/32 = 9.4%」。二者冲突时以
//   KEYMAP + captain 裁决为准（键位/档位语义属 KEYMAP 权威域）。
//   「严格静音」在本设计里由 **audio_en 门控** 实现，不靠音量档：
//   audio_en=0 时 sample_out 恒为 24'sd0（严格零，逐位全 0），
//   而 vol_lvl=0 只是最小音量而非静音。这样「静音开关」与「音量档」
//   两个概念各自独立、互不干扰，也避免了「用户把音量调到 0 就再也
//   听不到应急警报」这种配置陷阱（应急下还有 eff_lvl 钳位兜底）。
//
// 应急音量钳位（KEYMAP.md §5.1）
//   应急模式下 vol_lvl < 3 一律钳到档 3（13/32 ≈ 40.6%），
//   用 eff_lvl 派生信号实现，**不回写 vol_lvl 寄存器本身**：
//   用户设的档 0 仍被记住，退出应急自动恢复档 0。
//
// 数值表（增益 | 百分比 | 移位表达式 | x=8000 时的输出 | 近似 dB）
//   档 0 |  3/32 | (x>>>4)+(x>>>5)              |   750 | -20.6 dB
//   档 1 |  6/32 | (x>>>3)+(x>>>4)              |  1500 | -14.5 dB
//   档 2 | 10/32 | (x>>>2)+(x>>>4)              |  2500 | -10.1 dB
//   档 3 | 13/32 | (x>>>1)-(x>>>4)-(x>>>5)      |  3250 |  -7.8 dB
//   档 4 | 16/32 | (x>>>1)                      |  4000 |  -6.0 dB
//   档 5 | 20/32 | x-(x>>>2)-(x>>>3)            |  5000 |  -4.1 dB
//   档 6 | 23/32 | x-(x>>>2)-(x>>>5)            |  5750 |  -2.9 dB
//   档 7 | 26/32 | x-(x>>>3)-(x>>>4)            |  6500 |  -1.8 dB
//   档 8 | 29/32 | x-(x>>>4)-(x>>>5)            |  7250 |  -0.9 dB
//   档 9 | 32/32 | x                             |  8000 |   0.0 dB
//   dB 列按 20*log10(g/32) 计算，仅作说明，实现在整数域完成。
//
// 负数处理（为什么可以直接算术右移）
//   sample_in 是 24 位有符号二补数。Verilog 的 ">>>" 对 signed 操作数是
//   算术右移，符号位复制，不会丢符号。移位加对负数等价于
//   floor(x/2^k)，与真值最多差 1 LSB；单档最多叠 3 次移位，
//   最坏误差 ≤ 2 LSB（24 bit 满量程 8,388,608 的 2.4e-7），
//   听感与量化噪声同量级，可忽略。
//   验证要求：tb 里专测 x = -1 / -2 / -8388608 三点，断言
//   「输出符号不变、绝对值不增大、不出现正负振荡」。
// ============================================================================

`timescale 1ns/1ps

module vol_apply #(
    parameter [3:0] VOL_MAX = 4'd9      // 最高档号
)(
    input  wire               clk,
    input  wire               rst_n,
    // 样本流输入（来自 audio_src_mux）
    input  wire               sample_valid,   // 单拍：本拍 sample_in 有效
    input  wire signed [23:0] sample_in,
    // 控制
    input  wire [3:0]         vol_lvl,        // 用户音量档 0~9
    input  wire [1:0]         mode,           // 0=日常 1=科普 2=应急
    input  wire               audio_en,       // 音频总开关（已含应急强制 1）
    // 样本流输出（送往 pcm_to_pwm / audio_arc / audio_waveform）
    output reg                sample_valid_out,
    output reg  signed [23:0] sample_out,
    // 观测
    output wire [3:0]         eff_lvl         // 实际生效档位（含应急钳位）
);

    // ------------------------------------------------------------------
    // 应急音量下限钳位
    //   用 *_eff 派生信号，不回写 vol_lvl —— 与 key_router 里
    //   audio_en_eff / ticker_en_eff 同一手法。
    //   理由：应急是「临时覆盖」而不是「永久改配置」。若回写寄存器，
    //   用户退出应急后会发现音量莫名其妙变成 3 档，属于隐藏状态污染。
    // ------------------------------------------------------------------
    localparam [1:0] MODE_EMERG   = 2'd2;
    localparam [3:0] EMERG_MIN_LV = 4'd3;   // KEYMAP.md §5.1: 13/32 ≈ 40.6%

    wire [3:0] eff_lvl_w = (mode == MODE_EMERG && vol_lvl < EMERG_MIN_LV)
                           ? EMERG_MIN_LV : vol_lvl;
    assign eff_lvl = eff_lvl_w;

    // 档位越界保护：4 位输入可以到 15，超 VOL_MAX 一律按满幅处理
    wire [3:0] lvl_safe = (eff_lvl_w > VOL_MAX) ? VOL_MAX : eff_lvl_w;

    // ------------------------------------------------------------------
    // 增益函数：24 位有符号 × {3,6,10,13,16,20,23,26,29,32}/32
    //   中间值用 25 位有符号承接，容量足够：
    //     最大正数 8388607 × 32/32 = 8388607 < 2^23-1 ✔
    //     最大负数 -8388608 × 32/32 = -8388608 = -2^23 ✔（25 位绰绰有余）
    //   仍保留饱和分支作防御，避免将来改档位表时忘了扩位。
    // ------------------------------------------------------------------
    function signed [23:0] vol_gain;
        input signed [23:0] x;
        input        [3:0]  lvl;
        reg   signed [24:0] y;
        begin
            case (lvl)
                // 档 0: 3/32 = 9.375%（最轻）
                4'd0:    y = (x >>> 4) + (x >>> 5);
                // 档 1: 6/32 = 18.75%
                4'd1:    y = (x >>> 3) + (x >>> 4);
                // 档 2: 10/32 = 31.25%
                4'd2:    y = (x >>> 2) + (x >>> 4);
                // 档 3: 13/32 = 40.625%
                4'd3:    y = (x >>> 1) - (x >>> 4) - (x >>> 5);
                // 档 4: 16/32 = 50%
                4'd4:    y = (x >>> 1);
                // 档 5: 20/32 = 62.5%
                4'd5:    y = x - (x >>> 2) - (x >>> 3);
                // 档 6: 23/32 = 71.875%
                4'd6:    y = x - (x >>> 2) - (x >>> 5);
                // 档 7: 26/32 = 81.25%
                4'd7:    y = x - (x >>> 3) - (x >>> 4);
                // 档 8: 29/32 = 90.625%
                4'd8:    y = x - (x >>> 4) - (x >>> 5);
                // 档 9: 32/32 = 100%（最响，逐位直通）
                default: y = x;
            endcase
            // 饱和截断（当前档位表不可能触发，纯防御）
            if (y > 25'sd8388607)
                vol_gain = 24'sd8388607;
            else if (y < -25'sd8388608)
                vol_gain = -24'sd8388608;
            else
                vol_gain = y[23:0];
        end
    endfunction

    wire signed [23:0] scaled = vol_gain(sample_in, lvl_safe);

    // ------------------------------------------------------------------
    // 输出寄存（1 拍延迟）
    //   · 有样本时更新：audio_en=1 用缩放值，audio_en=0 严格输出 0
    //   · 无样本时**保持上一值**，不归零
    //     归零会产生一个满幅到 0 的阶跃，经 sigma-delta 调制后是
    //     明显的"咔哒"爆音；保持直流则被调制为恒定占空比，无声。
    //     这条与 wav_stream_player 的欠载策略一致（欠载也保持上一采样）。
    // ------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            sample_valid_out <= 1'b0;
            sample_out       <= 24'sd0;
        end else begin
            sample_valid_out <= sample_valid;
            if (sample_valid) begin
                sample_out <= audio_en ? scaled : 24'sd0;
            end
            // else: 保持 sample_out 不变（有意为之，见上）
        end
    end

endmodule
