// ============================================================================
// 文件名  : ratio_map.v
// 所在位置: rtl/video/ratio_map.v
// 所属层次: 视频层 / 图像路（Key9 五档屏占比映射）
// 权威依据: docs/plan_v2/ARCH_ADDENDUM_VIDEO_PATH.md §7.4（Key9 作用域）
//           ARCH_V2 :383-387（档位表）  KEYMAP_V2 :358-368（按键语义）
//           reports/plan_v2/PRECHECK_T7 §4.1 M-01（档位表复核）
// ============================================================================
// 【一】系统功能
//
//   Key9 把"图片在 640x480 屏上占多大"分成五档。本模块是纯粹的**查表器**：
//   把用户选择的档位 ratio_sel 翻译成四个几何参数，交给下游两个消费者：
//
//     win_w  ──┬─→ rtl/video/image_window_mask.v  的 win_w  （裁切窗口右边界）
//              └─→ rtl/video/pix_mosaic.v         的 src_w  （水平抽样源宽）
//     win_h  ──┬─→ rtl/video/image_window_mask.v  的 win_h  （裁切窗口下边界）
//              └─→ rtl/storage/pix_reader.v       的行映射参数（垂直方向，t4 负责）
//     win_off_x / win_off_y → image_window_mask 窗口左上角（居中偏移）
//
//   档位表（面积百分比 = win_w * win_h / (640*480)）：
//
//     ratio_sel  显示尺寸     偏移(off_x, off_y)   面积占比
//     ---------  ----------   ------------------   --------
//        0        320 x 240       (160, 120)        25.0 %
//        1        400 x 300       (120,  90)        39.1 %
//        2        480 x 360       ( 80,  60)        56.3 %
//        3        560 x 420       ( 40,  30)        76.6 %
//        4        640 x 480       (  0,   0)       100.0 %   ← 默认档
//
//   五档全部满足 2*off_x + win_w == 640 与 2*off_y + win_h == 480，即严格
//   水平/垂直居中。这两条不变式在 tb_pix_mosaic.v 里被独立断言（R5 / R6），
//   将来有人改档位表却忘了同步偏移，TB 会立刻报出来。
//
// 【二】为什么是纯组合、零寄存器
//
//   档位只随按键变化（人按一次 ~100 ms 的尺度），而几何参数每拍都要参与
//   比较。做成寄存器反而要多一级同步、多一组复位值，且改档后要等一拍才
//   生效。这里直接组合输出，改档在**当拍**即生效。约 30 LUT 的代价可接受，
//   也符合 RESOURCE_BUDGET.md 给的预算。
//
// 【三】未定义档位为什么落到"全屏"而不是"0x0"
//
//   如果在 case 的 default 里输出 0x0，image_window_mask 会把整个画面判成
//   窗口外（x_end = off_x + 0 = 0），屏幕直接全黑 —— 而 ratio_sel 是寄存器
//   输出，上电初值、按键抖动、在线调试误写都可能短暂出现 5/6/7 这些非法值。
//   全黑是很难定位的故障模式（看起来像"系统挂了"），因此 default 统一落到
//   640x480 全屏：最坏情况是"档位没生效，画面照常显示"，故障可见且无害。
//
// 【四】应急态钳位不在这里做
//
//   addendum :380 明确：disp_mode == 2'd2（应急）时几何参数强制为
//   640x480 / 偏移 (0,0)，且**不吞按键** —— 按键照常更新 ratio_sel，
//   退出应急后立刻恢复用户原先选的档位。
//
//   该钳位属于顶层（rtl/top/dmz_eg4s20_hdmi_top.v，t7 rtl-integ 负责）语义，
//   本模块不引入 disp_mode 端口。理由：钳位点必须与"应急画面来源"同源，
//   且要同时影响 win_*（本模块输出）与 pix_reader 的垂直映射、content_mux
//   的通路选择 —— 那是顶层的职责，塞进查表器只会让本模块长出第二个语义
//   分支，也让 TB 需要额外覆盖四种 disp_mode 组合。
//   ⇒ 给 rtl-integ 的接口约定：顶层例化时
//        wire [2:0] ratio_sel_eff = (disp_mode == 2'd2) ? 3'd4 : ratio_sel;
//      把 ratio_sel_eff 接到本模块即可，档位 4 的查表结果正是 640x480@(0,0)，
//      无需任何额外逻辑，也不改写 ratio_sel 寄存器（退出应急自动恢复）。
// ============================================================================

`timescale 1ns / 1ps

module ratio_map (
    input  wire [2:0]  ratio_sel,      // Key9 档位 0..4（5..7 视为非法）
    output reg  [10:0] win_w,          // 窗口宽 / 水平抽样源宽
    output reg  [9:0]  win_h,          // 窗口高 / 垂直行映射目标行数
    output reg  [10:0] win_off_x,      // 窗口左上角 x（水平居中偏移）
    output reg  [9:0]  win_off_y       // 窗口左上角 y（垂直居中偏移）
);

    // ------------------------------------------------------------------------
    // 档位译码
    //
    //   功能: ratio_sel -> 四个几何参数
    //   输入: ratio_sel
    //   输出: win_w / win_h / win_off_x / win_off_y
    //   ⚠️为什么用 always @(*) + case: 四个输出必须**同拍**更新，若拆成四条
    //      独立的 assign 条件表达式，综合器会生成四份并行比较逻辑（面积更
    //      大）；合成一个 case 更省 LUT，也更容易与档位表逐行核对。
    // ------------------------------------------------------------------------
    always @(*) begin
        case (ratio_sel)
            // 档 0: 1/4 面积（320x240）
            3'd0: begin
                win_w     = 11'd320;
                win_h     = 10'd240;
                win_off_x = 11'd160;
                win_off_y = 10'd120;
            end
            // 档 1: 约 5/12 面积（400x300）
            3'd1: begin
                win_w     = 11'd400;
                win_h     = 10'd300;
                win_off_x = 11'd120;
                win_off_y = 10'd90;
            end
            // 档 2: 约 9/16 面积（480x360）
            3'd2: begin
                win_w     = 11'd480;
                win_h     = 10'd360;
                win_off_x = 11'd80;
                win_off_y = 10'd60;
            end
            // 档 3: 约 3/4 面积（560x420）
            3'd3: begin
                win_w     = 11'd560;
                win_h     = 10'd420;
                win_off_x = 11'd40;
                win_off_y = 10'd30;
            end
            // 档 4（默认）: 全屏 640x480
            3'd4: begin
                win_w     = 11'd640;
                win_h     = 10'd480;
                win_off_x = 11'd0;
                win_off_y = 10'd0;
            end
            // 非法档位 5..7: 回落全屏，避免 image_window_mask 把画面全裁掉
            default: begin
                win_w     = 11'd640;
                win_h     = 10'd480;
                win_off_x = 11'd0;
                win_off_y = 10'd0;
            end
        endcase
    end

endmodule
