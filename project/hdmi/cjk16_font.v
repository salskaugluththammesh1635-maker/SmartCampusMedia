// ============================================================================
// 文件名  : cjk16_font.v
// 所在位置: rtl/osd/cjk16_font.v
// 所属层次: OSD 层 / 中文字模 ROM（BRAM）
// 作者    : 智播校园项目组
// ============================================================================
// 【一】系统功能
//   B1 扩展项"图层叠加与字幕"要求日常模式下屏幕底部显示一段中文校园介绍
//   滚动字幕。中文笔画无法用 8×16 ASCII 字模表现，必须自带 16×16 点阵字库。
//   本模块就是这个字库的唯一存储与读出端口。
//
// 【二】本模块功能
//       输入 {glyph[8:0], row[3:0]}  →  输出该字形该行的 16 位点阵
//
//   地址组织（FONT_ARCH_RULING.md §5.1）：
//       地址 = {glyph, row}，13 位，深度 8192
//       有效项 = 465 字形 × 16 行 = 7,440 项（其余 752 地址读回 16'h0000）
//       数据宽 = 16 位（一个 16×16 字形的整行）
//
//   为什么一个字形的 16 行是**连续地址**、而不是按 16 行分块：
//     滚动字幕在一行像素上停留 16 拍（像素时钟 25 MHz），t_row 在这 16 拍
//     内单调递增；把 row 放在地址低位，同一字形 16 行的点阵在存储器里是连续
//     的一段，块选择只需看地址高位，行内不需要重算块号。
//
// 【三】为什么用块 RAM 而不是逻辑查表
//   465 字形 × 16 行 × 16 位 = 119,040 bit。同样这份数据在不同例化上下文里
//   综合出来的 LUT 量能差 8.7 倍（实测 409 ~ 3,575 个），属于不可预测的支出；
//   而块 RAM 是**确定**的 16 块（8192 ÷ 512 = 16 段，512×18 配置），
//   利用率 119,040 / 147,456 = 80.7%。
//   当前设计 LUT 已用掉 77.16%、块 RAM 只用 26.56%——拿富余的换紧缺的，
//   这个判断不需要精确估算作依据（FONT_ARCH_RULING.md §4.1）。
//
// 【四】1 拍读延迟怎么补
//   块 RAM 的读出数据比地址晚 1 拍。本模块**不做任何地址预取**，而是把
//   同步延迟原样交出，由调用方 osd_caption 把"点阵 + 位索引 + 有效标记 +
//   中英标志"四个信号一起延后一拍配对使用（osd_caption.v 的【九】节）。
//
//   为什么绝对不能预取地址：video_timing_gen.v:207-208
//       active_x <= de_c ? (h_cnt - H_ACT_START) : 11'd0;
//       active_y <= de_c ? (v_cnt - V_ACT_START) : 10'd0;
//   消隐期 active_y 被强制归零，行号在行与行之间根本不可预测。任何
//   "提前一拍给地址"的实现在每行第一个字符的 16 拍内必然给出错误行号，
//   表现为点阵错乱——只在行首出现、不报错、仿真未必抓得到。
//
// 【五】存储器内容怎么装进去
//   用 $readmemh 在综合期装入，不引入厂商原语，也不手写七千多条 case。
//   这不是自创做法：工具厂商自己的可综合存储模板就是这么写的
//   （apm_memory.v 的 `$readmemh(MEMORY_INIT_FILE, memory)` 配
//   `ram_style = bram`，见 FONT_ARCH_RULING.md §5.4）。
//
//   数据文件 cjk16_bitmap.hex 与本源文件**同目录**，共 7,440 行、
//   每行恰好 4 个十六进制字符（16 bit），格式天然吻合 $readmemh。
//   路径写成不带目录前缀的 "cjk16_bitmap.hex"，含义是"仿真/综合时的
//   当前工作目录"——因此 scripts/sync_src.ps1 必须把 .hex 一起同步到
//   project/hdmi/ 并加入其 $map 白名单，否则综合出全零 BRAM 且**不报错**，
//   现象是字幕区域全空白（FONT_ARCH_RULING.md §5.4 路径约定）。
//
//   唯一的自检手段是 tb_osd_caption_cjk.v 的 V-11 断言：
//   读 glyph=0 的 row=1 必须等于 16'h3FF8（"日"字的第 1 行点阵）；
//   读到 16'h0000 即路径没解析到，按硬失败处理。
//
// 【六】为什么额外有 clk 端口
//   FONT_ARCH_RULING.md §7.8 的例化片段只写了 .glyph/.row/.pixels，
//   但同步读必须有时钟，故本模块补一个 clk 输入。除 clk 外端口与裁定一致。
//
// 【七】资源代价
//   16 块 BRAM9K（512×18 配置），LUT 消耗 0（读数据经块 RAM 输出寄存器直达
//   osd_caption 的 cjk_px 线上，只有块使能译码的小量逻辑）。
// ============================================================================
module cjk16_font (
    input  wire        clk,       // 像素时钟 25 MHz，同步读
    input  wire [8:0]  glyph,     // 字形索引 0..464（对应 cjk16_charset.txt 行首编号）
    input  wire [3:0]  row,       // 字形内行号 0..15（0 = 最上一行）
    output reg  [15:0] pixels     // 该行点阵，bit15 = 最左像素；比地址晚 1 拍
);

    // ========================================================================
    // 字库存储：8192 × 16 bit
    //   ram_style = bram 是本工程与工具厂商模板共用的推断标记，
    //   告诉综合器"这块请放块 RAM，不要摊成寄存器"。
    //   综合器若忽略该属性、按寄存器实现，M3 综合报告的 BRAM 计数会停在 17
    //   不涨——这正是"字库没进 BRAM"的可观测征兆之一。
    // ========================================================================
    reg [15:0] mem [0:8191] /* synthesis ram_style = bram */;

    integer init_i;

    initial begin
        // 先把整块存储器清零，再装入 7,440 行有效数据。
        //   为什么要这一步：数据文件只有 7,440 行，剩下 752 个地址（索引
        //   465..511 那段）没有被文件覆盖。真实块 RAM 上电就是全 0，读未
        //   收录字形得到空白；但仿真器里未被 $readmemh 覆盖的单元是 x，
        //   会让"未收录字符应当显示空白"这条行为在仿真中变成红色方框。
        //   显式清零后仿真与硬件行为一致，测试台的断言也就有了确定值。
        for (init_i = 0; init_i < 8192; init_i = init_i + 1) begin
            mem[init_i] = 16'h0000;
        end
        $readmemh("cjk16_bitmap.hex", mem);
    end

    // ========================================================================
    // 同步读：地址在本拍末尾锁存，数据在下一拍出现 —— 读延迟恰好 1 拍
    // ========================================================================
    always @(posedge clk) begin
        pixels <= mem[{glyph, row}];
    end

endmodule
