// =============================================================================
// pwm_audio_out.v — 底板 PWM 音频输出（测试音发生器 + PWM 数模调制）
// =============================================================================
// 【一、在整体系统中的功能】
//   所属层次 : 音频层（音频输出通道）
//   工程归属 : project/hdmi_td.al（HDMI 工程）；模块本身纯逻辑可跨工程复用
//   数据流位置:
//       DDS 相位累加器 ──→ 三角波表（组合） ──→ PWM 比较器 ──→ audio_pwm（单根 IO）
//            ↓
//       板上低通滤波 → 功率放大 → 3.5mm 接口 / 喇叭（模拟声）
//   为什么需要它:
//     赛规选题一基础要求③"基础音频输出"。底板载 "PWM 低通滤波和功率放大电路"
//     （[底板引脚说明 3.5]），FPGA 侧只需 1 个管脚 Audio_PWM=F3 输出占空比
//     调制信号即可出声 —— 无需 codec、无需 I2S，是当前阶段闭环基础要求③的
//     最小代价通路（HDMI 音频需换 APUG092 发送链，列入后续加分阶段）。
//
// 【二、本模块功能】
//   一句话职责: 用 DDS 合成指定频率的三角波测试音，再经 8bit PWM 调制成
//               单线音频信号（载波 ≈ f_clk/256 ≈ 97.7kHz，远超音频带外）。
//   关键特性:
//     - 音高由 FREQ_HZ 参数直接给定（默认 A4=440Hz 标准音），换音只改参数
//     - 三角波音色接近正弦、谐波少，比直接输出方波柔和悦耳
//     - mute 输入：静音时输出恒 0（占空比 0 = 0V 直流，对功放最安全）
//     - PWM 载波 97.7kHz >> 20kHz 音频上限，板载低通即可干净滤出包络
//
// 【三、接口与内部结构】
//   端口一览:
//     输入  clk        : 系统时钟（25MHz 像素时钟域）
//     输入  rst_n      : 低有效复位
//     输入  mute       : 静音控制（1=输出恒 0；阶段五接播放控制，现阶段接 0）
//     输出  audio_pwm  : PWM 音频输出（球 F3，接板载低通+功放）
//
//   内部逻辑块（共 2 块，按信号流顺序）:
//     [1] DDS 相位累加器        always @(posedge clk)
//           功能: 每拍累加 FTW（频率调谐字），相位回绕即完成一个波形周期；
//                 phase_acc[31] 是方向位，[30:23] 是当前幅值
//           输入: rst_n                          输出: phase_acc
//     [2] PWM 比较输出          always @(posedge clk)
//           功能: 8bit 自由计数器产生锯齿载波，与三角波幅值比较得占空比
//           输入: mute, 幅值, pwm_cnt             输出: pwm_cnt, audio_pwm
//     组合逻辑（不占块）: 三角波幅值 = phase_acc[31] ? ~phase_acc[30:23]
//                        : phase_acc[30:23]（一条三元表达式实现整张波形表，
//                        方向位取反幅值 = 下降沿，等价于 256 点三角波 ROM）
//
//   【板级事实】来源: 底板引脚说明 3.5（已核实）+ 底板例程 audioadc.adc
//     Audio_PWM = 球 F3；板载链路 = PWM → 低通滤波 → 功放 → 3.5mm/喇叭
//
// 【四、设计思路与范式】
//   主要范式 : 计数器/分频器 —— DDS 相位累加 + PWM 载波计数，两个计数器构成本模块
//   次要范式 : 组合译码 —— 三角波表与占空比比较都是纯组合
//   为什么这样写:
//     1) DDS（直接数字频率合成）公式: f_out = FTW × f_clk / 2^32，
//        反解 FTW = FREQ_HZ × 2^32 / CLK_FREQ_HZ。440Hz @25MHz → FTW = 75594，
//        实际输出 439.997Hz（误差 <0.001%）。比"数半周期翻转"方案精度高得多，
//        且波形相位连续，改频率无毛刺
//     2) 三角波表不占存储: phase_acc[31] 天然是方向位，对其余高位取反即得
//        下降半周 —— 一行逻辑替代 256 点 ROM，无需 initial 块、无块 RAM
//     3) PWM 载波取 f_clk/256: 8bit 计数器自由跑（25MHz/256≈97.7kHz）。
//        载波必须远高于音频上限（20kHz）否则落入带内成啸叫；也不必更快，
//        8bit 精度对"测试音验证通路"足够（官方 wav_to_mif 路径同为 8bit 样本）
//     4) FTW 用 64 位中间量再除: FREQ_HZ × 2^32 ≈ 1.89×10^12 超 32 位范围，
//        必须显式声明 [63:0] 再做常量除法（综合器常量折叠，无时序代价）
//   与 buzzer_tone 的区别: 蜂鸣器走"数半周期翻转"出**方波**（提示音），
//     本模块走 DDS 出**幅值序列**再 PWM 调制（可承载任意波形的音频通路）。
//     两模块驱动不同器件（H11 蜂鸣器 / F3 音频座），互不冲突
//   范式认读方法: 见 docs/design_patterns.md
// =============================================================================
`timescale 1ns / 1ps

module pwm_audio_out #(
    parameter CLK_FREQ_HZ = 25_000_000,  // 系统时钟频率(Hz)。作用: DDS 与 PWM 载波的
                                         //   时间基准；换时钟只改这里，逻辑一行不动
    parameter FREQ_HZ     = 440          // 测试音频率(Hz)。作用: 决定听到的音高；
                                         //   默认 A4=440Hz 标准音，与蜂鸣器 C5 提示音
                                         //   音高错开，现场可分辨"音频座在响"还是"蜂鸣器在响"
)(
    input  wire       clk,         // 系统时钟（25MHz）
    input  wire       rst_n,       // 低有效复位
    input  wire       mute,        // 静音控制: 1=输出恒 0（阶段五接播放控制）
    output reg        audio_pwm    // PWM 音频输出（球 F3，占空比 = 波形幅值/256）
);

    // ===== 由 parameter 推导的频率调谐字（改音高/时钟只需动上面两个参数）=====
    // DDS 公式: f_out = FTW × f_clk / 2^32  →  FTW = FREQ_HZ × 2^32 / CLK_FREQ_HZ
    // 440Hz @ 25MHz: FTW = 440 × 4294967296 / 25000000 = 75594（实际 439.997Hz）
    localparam [63:0] FTW_WIDE = FREQ_HZ * 64'd4294967296;
                        // ↑ 作用: 64 位中间量。FREQ_HZ × 2^32 ≈ 1.89×10^12 远超 32 位，
                        //   若直接做 32 位乘法会溢出，必须显式加宽后再除
    localparam [31:0] FTW = FTW_WIDE / CLK_FREQ_HZ;
                        // ↑ 作用: 每拍累加的"步进"。数值越大音高越高；
                        //   综合器把它折叠成常数，无任何时序/面积代价

    reg [31:0] phase_acc;  // 【DDS 相位累加器】高 8 位 [31:24] = 当前波形相位（0~255 拍）
                           //   作用: 每拍加 FTW，回绕一次 = 波形一个完整周期；
                           //   [31] 是三角波方向位（0=上升沿 / 1=下降沿）
    reg [7:0]  pwm_cnt;    // 【PWM 载波计数器】自由运行的 8bit 锯齿波
                           //   作用: 与波形幅值比较产生占空比；载波 = f_clk/256 ≈ 97.7kHz

    // ---- 三角波幅值（组合）: 方向位取反低位幅值 = 下降半周，一行替代 256 点 ROM ----
    wire [7:0] wave_amp = phase_acc[31] ? ~phase_acc[30:23]   // 下半周: 幅值递减（取反）
                                        :  phase_acc[30:23];  // 上半周: 幅值递增
                           // 【当前波形幅值】0~255，128 为中心值
                           //   作用: 直接决定 PWM 占空比（amp/256）

    // ------------- always 块 ① / 共 2 块: DDS 相位累加 -------------
    // 功能: 相位每拍前进一步（+FTW），实现固定频率的波形相位推进
    // 输入: clk, rst_n            输出: phase_acc
    // 说明: FTW 为常数，此块永远只做一次 32 位加法 —— 整个模块唯一的"运算"
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            phase_acc <= 32'd0;
        else
            phase_acc <= phase_acc + FTW;
    end

    // ------------- always 块 ② / 共 2 块: PWM 载波计数 + 占空比输出 -------------
    // 功能: 8bit 计数器自由跑产生 97.7kHz 锯齿载波；计数器 < 幅值时输出高，
    //       占空比 = wave_amp/256；mute 时强制输出 0（占空比 0 = 0V 直流）
    // 输入: clk, rst_n, mute, wave_amp    输出: pwm_cnt, audio_pwm
    // 说明: audio_pwm 与 pwm_cnt 同块赋值（同一状态组），避免多驱动
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            pwm_cnt   <= 8'd0;
            audio_pwm <= 1'b0;            // 复位态 = 静音（0V 直流，功放最安全）
        end
        else begin
            pwm_cnt <= pwm_cnt + 8'd1;    // 载波自由计数（256 拍一循环）
            if (mute)
                audio_pwm <= 1'b0;
            else
                audio_pwm <= (wave_amp > pwm_cnt);  // 占空比 = wave_amp/256
        end
    end

endmodule
