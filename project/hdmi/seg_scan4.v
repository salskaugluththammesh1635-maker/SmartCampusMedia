// =============================================================================
// seg_scan4.v — 4 位数码管动态扫描驱动
// =============================================================================
// 【一、在整体系统中的功能】
//   所属层次 : 显示层（数码管显示链路的驱动级）
//   工程归属 : bringup_td.al 与 hdmi_td.al **两个工程共用**
//   数据流位置:
//       seg_decoder 输出的 4 组段码（dig0 ~ dig3）
//            ↓
//       【本模块】──→ seg_data[7:0] （段选：点亮哪几段）
//            └─────→ seg_cs[3:0]   （位选：当前点亮哪一位）
//            ↓
//       板上 4 位数码管（COM0 最右 … COM3 最左）
//   为什么需要它:
//     4 位数码管若"同时点亮"，需要 4×8 = 32 根段线；采用动态扫描只需
//     8 根段线 + 4 根位选线 = 12 根。代价是任一时刻只有一位真正点亮，
//     靠每秒 1000 轮的高速轮换 + 人眼视觉暂留，看起来像 4 位同时亮。
//
// 【二、本模块功能】
//   一句话职责: 用 12 根线驱动 4 位数码管，靠高速轮流点亮实现"看起来同时显示"。
//   关键特性:
//     - 整轮刷新 1kHz（每位 250µs），远高于人眼可感的闪烁阈值
//     - 输出采用"组合算 next 值 + 时序统一寄存"结构（本项目编码规范）
//     - 位选为**独热低**（同一时刻只有一位是 0，其余为 1）
//     - 复位/消影时段码给 8'h00（高电平点亮语义下的"全灭"，2026-10-17 上板修正）
//
// 【三、接口与内部结构】
//   端口一览:
//     输入  clk            : 系统时钟（25MHz）
//     输入  rst_n          : 低有效复位
//     输入  dig0~dig3[7:0] : 4 位段码输入，{DP,G,F,E,D,C,B,A}，高电平点亮
//                            （dig0 = 最右位，dig3 = 最左位）
//     输出  seg_data[7:0]  : 段选输出（送数码管段线）
//     输出  seg_cs[3:0]    : 位选输出（seg_cs[0] = COM0 = 最右位），低电平选通
//
//   内部逻辑块（共 3 块）:
//     [1] 扫描节拍 + 位索引   always @(posedge clk)
//           功能: 计数器分频产生 1kHz 轮转节拍；dig_idx 0→1→2→3 循环
//           输入: clk, rst_n                输出: dig_idx[1:0]
//     [2] 段码/位选组合译码   always @(*)   中间寄存器 seg_data_nxt / seg_cs_nxt
//           功能: 依 dig_idx 选出当前位的段码，并产生独热低的位选
//           输入: dig_idx, dig0~dig3        输出: seg_data_nxt, seg_cs_nxt
//     [3] 输出寄存器          always @(posedge clk)
//           功能: 把 next 值寄存输出（规避同块内混用 = 与 <=）
//           输入: seg_data_nxt, seg_cs_nxt  输出: seg_data, seg_cs
//
//   【板级事实】来源: 官方底板例程 seg_led_decoder.v + seg_sel_decoder.v
//     （AudioADC 工程，段选/位选引脚与本板一致），2026-10-17 上板实测确认
//     段选 Digitron_Out[7:0]: **高电平点亮**（1=亮，0=灭，全 0 = 全灭）
//       —— 早期按"走近FPGA"例程推断为低电平点亮，上板显示全错后修正。
//          两套官方资料极性相反时，以上板实测+同引脚官方例程为准
//     位选 DigitronCS_Out[3:0]: **低电平选通**（官方 seg_sel_decoder.v:
//       00→4'b1110 … 独热低，与本模块实现一致）
//     位序: COM0(最右) ~ COM3(最左)
//
// 【四、设计思路与范式】
//   主要范式 : 线性序列机（LSM）—— dig_idx 无条件循环 0→1→2→3
//   次要范式 : 计数器分频（产生扫描节拍）+ 组合译码（选段码/选位）+ 打拍（输出寄存）
//   为什么这样写:
//     "动态扫描"是数码管驱动的标准方案：**用时间换引脚**。代价是亮度降到 1/4
//     （每位只亮 25% 的时间），所以扫描频率必须足够高，靠视觉暂留补回观感。
//   关键写法要点:
//     1) **组合算 next + 时序统一寄存**: 这是本项目为规避"同一 always 块内混用
//        `=` 与 `<=`"而定下的规范结构。早期直接在一个时序块里混用，被安路 TD
//        报 `mixed blocking and non-blocking assignments` ERROR；更隐蔽的是，
//        非阻塞赋值会在时间步末**覆盖**阻塞赋值的效果，导致位选恒为全 1
//        （数码管实际全灭）—— 这个坑曾真实发生，让调试绕了弯路
//     2) 消影（防重影）: 切换位选时，段码应处于"全灭"状态，避免上一位的残影
//        串到下一位。本例用"组合默认值 = 全灭（8'h00）"实现
//     3) 复位值必须是"灭"而非"亮": 在高电平点亮的语义下，8'hFF 是**全亮**、
//        8'h00 才是全灭。极性改版时复位值/消影值/顶层空位填充值必须三者同改
//   范式认读方法: 见 docs/design_patterns.md
// =============================================================================
`timescale 1ns / 1ps

module seg_scan4 #(
    parameter CLK_FREQ_HZ = 50_000_000,  // 系统时钟频率(Hz)。作用: 把"刷新率"换算成分频
                                         //   计数值；换时钟（50M→25M）只改这里，逻辑不动
    parameter SCAN_HZ     = 1000         // 整轮刷新率(Hz)。作用: 决定轮询 4 位数码管的速度。
                                         //   1000 = 每秒完整轮询 1000 次（每位停留 250µs）。
                                         //   太低（<100Hz）会看到明显闪烁；越高刷新越稳
)(
    input  wire       clk,
    input  wire       rst_n,
    input  wire [7:0] dig0,              // 最右位段码 {DP,G,F,E,D,C,B,A}（含 DP 于 bit7）
    input  wire [7:0] dig1,
    input  wire [7:0] dig2,
    input  wire [7:0] dig3,              // 最左位
    output reg  [7:0] seg_data,          // 段选输出（低电平点亮: 0=亮, 1=灭）
    output reg  [3:0] seg_cs             // 位选输出（低选通）: seg_cs[0]=COM0(最右)
);
    localparam SCAN_DIV = CLK_FREQ_HZ / (SCAN_HZ * 4) - 1;
    //   ↑ 作用: 每一位数码管停留的时钟周期数 - 1（即位切换的计数值）
    //     推导: 一轮要轮询 4 位，故每位停留时间 = 1 / (SCAN_HZ × 4)
    //           25MHz 时钟下: 25_000_000/(1000×4) - 1 = 6249 → 每位约 250µs
    //     用法: div_cnt 数到 SCAN_DIV 时切换下一位（dig_idx 递增、行末归零）

    reg [23:0] div_cnt;     // 【位切换分频计数器】每个时钟沿 +1，数到 SCAN_DIV 归零
                            //   作用: 把系统时钟"降速"成位切换节拍（每位 250µs）
                            //   位宽 24 位足够（25MHz 时需数到 6250）
    reg [1:0]  dig_idx;     // 【当前点亮的位序号】0~3 循环
                            //   0 = 最右位 COM0，3 = 最左位 COM3
                            //   作用: 决定本拍送出哪一位的段码、以及把哪个位选拉低

    // ================= always 块 ① / 共 3 块: 扫描节拍与位序号 =================
    // 功能: ① div_cnt 分频计数，数满一位的停留时间（SCAN_DIV）就归零
    //       ② dig_idx 在每次节拍时加一（0→1→2→3→0），实现"轮询点亮"
    // 输入: clk, rst_n, div_cnt          输出: div_cnt, dig_idx
    // 说明: 节拍判定直接写成 `div_cnt == SCAN_DIV` 比较，未单独引出 tick 信号
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) 
        begin
            div_cnt <= 24'd0;
            dig_idx <= 2'd0;
        end
        else if (div_cnt == SCAN_DIV) 
        begin
            div_cnt <= 24'd0;
            dig_idx <= dig_idx + 2'd1;
        end
        else
            div_cnt <= div_cnt + 24'd1;
    end

    // 输入排列: {dig3,dig2,dig1,dig0} = {最左,...,最右}
    // 输出排列: seg_cs[0]=COM0 最右位 ... seg_cs[3]=COM3 最左位
    //
    // 结构说明: 组合逻辑先算出 next 值, 时序逻辑统一寄存
    //   —— 避免同一变量在时序块内混用阻塞/非阻塞赋值
    //   （安路 TD 综合器对混用直接报 ERROR）
    reg [7:0] seg_data_nxt; // 【组合中间值】下一拍要输出的段码
                            //   作用: 由 dig_idx 从 dig0~dig3 中选出当前位的段码；
                            //         组合默认值为 8'h00（全灭 → 实现消影防重影）
    reg [3:0] seg_cs_nxt;   // 【组合中间值】下一拍要输出的位选（独热低）
                            //   作用: 默认 4'b1111（全不选通），再由 case 把当前位拉低
                            //   说明: 这两个 next 变量是"组合算、时序统一寄存"结构的一半，
                            //         目的是避免同一 always 块内混用 = 与 <=（TD 会报错）

    // ========== always 块 ② / 共 3 块: 段码与位选的组合译码 ==========
    // 功能: 按 dig_idx 从 dig0~dig3 中选出当前位的段码，并把对应位选拉低（独热低）；
    //       默认值设为"全灭 + 全不选通"，从而在切换瞬间实现消影（防重影）
    // 输入: dig_idx, dig0~dig3          输出: seg_data_nxt, seg_cs_nxt
    // 说明: 纯组合逻辑（无时钟），故用阻塞赋值 =；结果交由块③统一寄存输出
    always @(*) begin
        seg_cs_nxt   = 4'b1111;            // 默认: 全部位选不选通
        seg_data_nxt = 8'h00;              // 默认: 段全灭（高电平点亮 → 全 0 才是灭; 消影防重影）
        case (dig_idx)
            2'd0: 
                begin seg_cs_nxt[0] = 1'b0; seg_data_nxt = dig0; end
            2'd1: 
                begin seg_cs_nxt[1] = 1'b0; seg_data_nxt = dig1; end
            2'd2: 
                begin seg_cs_nxt[2] = 1'b0; seg_data_nxt = dig2; end
            2'd3: 
                begin seg_cs_nxt[3] = 1'b0; seg_data_nxt = dig3; end
            default: ;
        endcase
    end

    // ============ always 块 ③ / 共 3 块: 输出寄存器（统一寄存）============
    // 功能: 把块②算出的 next 值寄存一拍再输出，使驱动数码管的信号干净无毛刺
    // 输入: clk, rst_n, seg_data_nxt, seg_cs_nxt
    // 输出: seg_data, seg_cs（直接连到数码管引脚）
    // 说明: 这是本项目"组合算 next + 时序统一寄存"规范的后半部分 ——
    //       目的是避免同一变量在时序块内混用 = 与 <=（安路 TD 会直接报 ERROR）
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            seg_data <= 8'h00;             // 复位全灭（高电平点亮, 全 0 = 灭）
            seg_cs   <= 4'b1111;           // 全不选通
        end
        else begin
            seg_data <= seg_data_nxt;
            seg_cs   <= seg_cs_nxt;
        end
    end

endmodule
