// =============================================================================
// dmz_eg4s20_min_top.v — 阶段二：最小系统上板自检顶层
// =============================================================================
// 【一、在整体系统中的功能】
//   所属层次 : 顶层（Top Level）—— 最小系统工程的"总装配图"
//   工程归属 : project/bringup_td.al（**已在板卡上跑通并验证通过**）
//   数据流位置:
//       50MHz 晶振(R7) → 【本模块】→ 键盘扫描 / 数码管 / LED / 蜂鸣器
//       本工程**不含视频与存储**，目标只有一个: 用最少的模块把板子的时钟、
//       复位、按键、显示、发声全部验证一遍
//   为什么需要它（本工程存在的价值）:
//     1) **分层排错**: 完整系统（HDMI 工程）出问题时最怕分不清"板子坏"还是
//        "代码错"。最小系统先跑通，就把"板级基础"这一层排除掉了 ——
//        剩下的问题必然在视频/存储链路上
//     2) **管脚验证**: 31 个 IO 全部经过上板实测，与约束文件一一对应
//     3) **后续顶层的模板**: HDMI 顶层原封不动复用了本模块的 4 个子模块，
//        行为完全一致 —— 这正是"子模块可跨工程复用"设计价值的体现
//
// 【二、本模块功能】
//   一句话职责: 按一下键 → 计数加一 → 数码管/LED/蜂鸣器给出反馈。
//   上板可验证项（每一项对应一类板级资源的验证）:
//     1) 时钟与复位: 数码管最左位小数点 1Hz 闪烁 = 50MHz 时钟与复位都正常
//     2) 矩阵键盘  : 按键计数递增 = 行扫描与消抖正常
//     3) 数码管    : 显示十进制计数 0000~9999 = 动态扫描正常
//     4) LED       : 高 4 位 = 最近键号，低 4 位 = 计数个位
//     5) 蜂鸣器    : 每次按键短鸣 100ms
//
// 【三、接口与内部结构】
//   端口一览（共 31 个 IO）:
//     输入  clk            : 50MHz 系统时钟（球 R7）
//     输入  rst_n_btn      : 复位按键（球 E3，低有效）
//     输出  key_row[3:0]   : 键盘行扫描（E10/C10/F9/D9，低电平选通）
//     输入  key_col[3:0]   : 键盘列回读（E11/D11/C11/F10，板上 10k 上拉）
//     输出  led[7:0]       : LED（B14…F16，高电平点亮，与 R-2R DAC 复用）
//     输出  seg_data[7:0]  : 数码管段选（A4/A6/B8/E8/A7/B5/A8/C8，低电平点亮）
//     输出  seg_cs[3:0]    : 数码管位选（C9/B6/A5/A3，低电平选通）
//     输出  buzzer         : 蜂鸣器（球 H11，低电平响）
//
//   内部逻辑块（共 6 块 + 1 条 assign）:
//     [1] key_matrix_4x4          子模块例化
//           功能: 键盘扫描 + 20ms 逐键消抖 + 按下事件输出
//           输入: clk, rst_n_btn, key_col    输出: key_event, key_code, key_state
//     [2] BCD 计数器（内联）      always @(posedge clk)
//           功能: 按键事件驱动 4 位十进制计数（带逐级进位）；直接产生显示码，
//                 省掉"二进制 → BCD"的转换逻辑
//           输入: key_event, key_code        输出: bcd3/bcd2/bcd1/bcd0, last_key
//     [3] 1Hz 心跳发生器（内联）  always @(posedge clk)
//           功能: 每 0.5 秒翻转 hb_flag，驱动数码管最左位小数点闪烁（"系统活着"指示）
//           输入: clk, rst_n_btn             输出: hb_flag
//     [4] seg_decoder ×4          子模块例化
//           功能: 4 位 BCD 数字 → 4 组 7 段码
//           输入: bcd3~bcd0                  输出: seg3~seg0
//     [5] seg_scan4               子模块例化
//           功能: 4 组段码 → 动态扫描输出（最左位 DP 接心跳信号）
//           输入: seg3~seg0, hb_flag         输出: seg_data, seg_cs
//     [6] buzzer_tone             子模块例化
//           功能: 按键时短鸣 100ms（C5≈523Hz）
//           输入: key_event                  输出: buzzer
//     [7] LED 输出                assign（组合）
//           功能: led = {last_key, bcd0}（高 4 位 = 最近键号，低 4 位 = 计数个位）
//           输入: last_key, bcd0             输出: led[7:0]
//
//   【板级事实】来源: 走近FPGA 表1.1~1.6 + 核心板原理图 p2/p4（全部已核实）
//     clk=R7(50MHz)  rst_n_btn=E3(按下为低)  buzzer=H11(PNP 驱动，低电平响)
//     矩阵键盘 行 E10/C10/F9/D9（输出扫描），列 E11/D11/C11/F10（输入，10k 上拉）
//     LED0~7 = B14/B15/B16/C15/C16/E13/E16/F16（高电平点亮）
//     数码管 段 A4/A6/B8/E8/A7/B5/A8/C8，位选 C9/B6/A5/A3（段低电平点亮）
//
// 【四、设计思路与范式】
//   主要范式 : 结构化装配（Structural）—— 顶层只做例化与连线
//   次要范式 : 计数器分频（心跳发生器）、级联计数器进位（BCD 计数）、
//              组合译码（LED 位拼接）
//   为什么这样写:
//     1) **为什么顶层几乎不含算法**: 顶层只负责"装配"与"全局事务"（时钟、
//        复位、管脚）。算法放在子模块里才能独立仿真、跨工程复用 ——
//        本模块的 4 个子模块在 HDMI 工程中被原样再次使用
//     2) **为什么 BCD 计数器用内联写法而不是做成独立模块**: 它只服务本顶层、
//        代码量小（十几行）、且与"按键计数"这个具体场景强耦合。
//        判据: 若某段逻辑需要被第二个模块复用，就该拆成独立模块
//     3) **为什么用 BCD 计数而不是二进制计数**: 数码管要显示十进制，BCD 天然
//        对齐显示需求，省掉"二进制→BCD"的除法/取模逻辑（那会消耗大量资源）
//     4) **为什么用 `~hb_flag` 接 DP**: 数码管段码是低电平点亮，故 DP 位为 0
//        时亮。hb_flag 每 0.5 秒翻转，取反后 DP 便有 1Hz 的亮灭变化
//   关键写法要点:
//     - 例化时**显式写参数**（`#(.CLK_FREQ_HZ(50_000_000))`），不依赖默认值 ——
//       换时钟频率时一眼就能看到所有需要同步修改的地方
//     - 端口连接一律用"命名连接"（`.clk(clk)`）而非位置连接，
//       避免子模块端口顺序调整时接错线
//   范式认读方法: 见 docs/design_patterns.md
// =============================================================================
`timescale 1ns / 1ps

module dmz_eg4s20_min_top (
    input  wire        clk,           // 50MHz, 球 R7
    input  wire        rst_n_btn,     // RSTn 按键, 球 E3, 低有效
    // 4x4 矩阵键盘
    output wire [3:0]  key_row,       // E10,C10,F9,D9（低电平扫描选通）
    input  wire [3:0]  key_col,       // E11,D11,C11,F10（上拉, 按下为低）
    // LED（高电平点亮）
    output wire [7:0]  led,           // B14,B15,B16,C15,C16,E13,E16,F16
    // 数码管（段低电平点亮 / 位低电平选通）
    output wire [7:0]  seg_data,      // A4,A6,B8,E8,A7,B5,A8,C8（字节序 {DP,G,F,E,D,C,B,A}）
    output wire [3:0]  seg_cs,        // C9,B6,A5,A3
    // 蜂鸣器（低电平响）
    output wire        buzzer         // H11
);

    // -------------------------------------------------------------------------
    // 1. 矩阵键盘：扫描 + 消抖 + 按下事件
    // -------------------------------------------------------------------------
    wire        key_event;   // 【按键事件】单拍脉冲，1 = 有键刚被按下（来自键盘模块）
                             //   作用: 驱动计数递增、蜂鸣器发音、LED 更新
    wire [3:0]  key_code;    // 【键号】0~15，标识具体是哪个键被按下
    wire [15:0] key_state;   // 【键状态位图】16 键的稳定状态（本顶层未使用，
                             //   综合时会自动优化掉；保留连接便于将来扩展）

    key_matrix_4x4 #(
        .CLK_FREQ_HZ (50_000_000),
        .DEBOUNCE_MS (20)
    ) u_key (
        .clk       (clk),
        .rst_n     (rst_n_btn),
        .key_row   (key_row),
        .key_col   (key_col),
        .key_event (key_event),
        .key_code  (key_code),
        .key_state (key_state)
    );

    // -------------------------------------------------------------------------
    // 2. 按键计数（4 位 BCD, 0~9999）与最近键号
    //    用 BCD 计数器直接产生显示码, 免去二进制→BCD 转换逻辑
    // -------------------------------------------------------------------------
    reg [3:0] bcd3, bcd2, bcd1, bcd0;   // 【4 位十进制计数器的各位】
                                        //   bcd3=千位 bcd2=百位 bcd1=十位 bcd0=个位
                                        //   作用: 直接存放"显示用"的十进制数字，
                                        //         省去二进制→BCD 的转换逻辑（很费资源）
    reg [3:0] last_key;                 // 【最近按下的键号】用于 LED 高 4 位显示，
                                        //   便于上板时确认"我按的是哪个键"（键序核对用）

    // ========== always 块 ① / 共 2 块: 按键计数（4 位十进制 BCD）==========
    // 功能: 每来一个按键事件就把个位加一，并逐级进位（个→十→百→千）；
    //       超过 9999 自动回绕到 0000；同时记录最近按下的键号
    // 输入: clk, rst_n_btn, key_event, key_code
    // 输出: bcd3 / bcd2 / bcd1 / bcd0（各位十进制数字）, last_key
    // 说明: 直接用 BCD 而非二进制计数，是为了天然对齐数码管的十进制显示需求，
    //       省掉"二进制 → BCD"的除法/取模逻辑（那会消耗大量 LUT 资源）
    always @(posedge clk or negedge rst_n_btn) begin
        if (!rst_n_btn) begin
            bcd3 <= 4'd0;
            bcd2 <= 4'd0;
            bcd1 <= 4'd0;
            bcd0 <= 4'd0;
            last_key <= 4'd0;
        end
        else if (key_event) begin
            last_key <= key_code;
            // BCD 递增（带进位）
            if (bcd0 != 4'd9) begin
                bcd0 <= bcd0 + 4'd1;
            end
            else begin
                bcd0 <= 4'd0;
                if (bcd1 != 4'd9) begin
                    bcd1 <= bcd1 + 4'd1;
                end
                else begin
                    bcd1 <= 4'd0;
                    if (bcd2 != 4'd9) begin
                        bcd2 <= bcd2 + 4'd1;
                    end
                    else begin
                        bcd2 <= 4'd0;
                        if (bcd3 != 4'd9)
                            bcd3 <= bcd3 + 4'd1;
                        else
                            bcd3 <= 4'd0;
                    end
                end
            end
        end
    end

    // -------------------------------------------------------------------------
    // 3. 1Hz 心跳（用于数码管千位小数点闪烁, 证明时钟/PLL 正常）
    // -------------------------------------------------------------------------
    reg [25:0] hb_cnt;      // 【心跳计数器】累计时钟周期数，数到 24,999,999（0.5 秒）归零
                            //   位宽 26 位: 24,999,999 < 2^25，留 1 位余量
    reg        hb_flag;     // 【心跳标志】每 0.5 秒翻转一次
                            //   作用: 取反后接到数码管最左位的小数点 → 形成 1Hz 闪烁，
                            //         这是上板时"系统活着"的第一眼判据（时钟+复位都正常的证据）
    // ================= always 块 ② / 共 2 块: 1Hz 心跳 =================
    // 功能: hb_cnt 累计到 0.5 秒时令 hb_flag 翻转一次 —— 即产生 1Hz 方波
    // 输入: clk, rst_n_btn            输出: hb_cnt, hb_flag
    // 说明: 典型的"计数器分频"用法，把 50MHz 降成人眼可辨的 1Hz。
    //       它的价值不在功能而在**可观测性**：一上电就能凭小数点闪烁判断
    //       "时钟在跑、复位已释放"，避免黑屏时无从下手排查
    always @(posedge clk or negedge rst_n_btn) begin
        if (!rst_n_btn) begin
            hb_cnt  <= 26'd0;
            hb_flag <= 1'b0;
        end
        else if (hb_cnt >= 26'd24_999_999) begin   // 0.5s 翻转 → 1Hz 闪烁
            hb_cnt  <= 26'd0;
            hb_flag <= ~hb_flag;
        end
        else begin
            hb_cnt <= hb_cnt + 26'd1;
        end
    end

    // -------------------------------------------------------------------------
    // 4. 数码管显示: 千位(带心跳 DP) 百位 十位 个位 = 按键计数
    // -------------------------------------------------------------------------
    wire [6:0] seg3, seg2, seg1, seg0;
                            // 【4 组段码】由 4 个 seg_decoder 分别把 bcd3/bcd2/bcd1/bcd0
                            //   译码得到（seg3 对应千位，seg0 对应个位）
                            //   位序: {g,f,e,d,c,b,a}，高电平点亮（2026-10-17 上板修正）
    seg_decoder u_dec3 (.bin_data (bcd3), .seg_data (seg3));
    seg_decoder u_dec2 (.bin_data (bcd2), .seg_data (seg2));
    seg_decoder u_dec1 (.bin_data (bcd1), .seg_data (seg1));
    seg_decoder u_dec0 (.bin_data (bcd0), .seg_data (seg0));

    seg_scan4 #(
        .CLK_FREQ_HZ (50_000_000),
        .SCAN_HZ     (1000)
    ) u_seg (
        .clk      (clk),
        .rst_n    (rst_n_btn),
        .dig0     ({1'b0, seg0}),        // 最右位: 个位（DP 灭）
        .dig1     ({1'b0, seg1}),        // 次右位: 十位
        .dig2     ({1'b0, seg2}),        // 次左位: 百位
        .dig3     ({hb_flag, seg3}),     // 最左位: 千位（DP = 心跳, 高电平点亮: 计数时亮）
        .seg_data (seg_data),
        .seg_cs   (seg_cs)
    );

    // -------------------------------------------------------------------------
    // 5. LED: 高 4 位 = 最近按键号, 低 4 位 = 计数个位
    // -------------------------------------------------------------------------
    assign led = {last_key, bcd0};

    // -------------------------------------------------------------------------
    // 6. 蜂鸣器: 每次按键短鸣 100ms（C5≈523Hz）
    // -------------------------------------------------------------------------
    buzzer_tone #(
        .CLK_FREQ_HZ (50_000_000)
    ) u_buzz (
        .clk        (clk),
        .rst_n      (rst_n_btn),
        .tone_sel   (2'd1),              // 按键音模式
        .trig       (key_event),
        .buzzer_out (buzzer)
    );

endmodule
