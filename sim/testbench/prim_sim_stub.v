// prim_sim_stub.v —— 安路（Anlogic）原语的纯行为仿真替代模型
// -----------------------------------------------------------------------------
// 已弃用（DEPRECATED）：当前没有任何脚本或 testbench 引用本文件。
// 请改用安路官方仿真库 <TD install>\sim_release\eg4\ 下的原语模型，
// 参考 sim/scripts/run_unit_coverage_regression.ps1 与 TEST_COVERAGE.md 第五节。
// 保留本文件仅供对照：它的上下沿分工与官方 EG_LOGIC_ODDR 相反。
// -----------------------------------------------------------------------------
// 【为什么当初需要这个文件】
//   rtl/video/hdmi/ 下的串化链路直接例化了安路原语：
//     - lane_lvds_10_1.v  → EG_LOGIC_ODDR
//   ModelSim 里没有安路的原语库，不提供这段行为模型就无法 vlog 编译，
//   更无法做 HDMI 物理层的单元验证。
//
// 【本文件只做"行为等价"，不做"时序等价"】
//   原语的真实延迟、输出摆率、差分对电气特性无法在 RTL 仿真中体现。
//   本文件只保证：给定 d0/d1/clk/rst，输出的逻辑值与原语语义一致。
//   ⚠️ 因此本文件的验证结论只覆盖"逻辑正确性"，不覆盖物理层时序。
//   ⚠️ 只在仿真时编译本文件，绝不能进入综合工程（rtl/ 目录下没有它）。
//
// 【EG_LOGIC_ODDR 的语义（EG4 系列）】
//   d0 在 clk 上升沿被采到 q；d1 在 clk 下降沿被采到 q。
//   即一个时钟周期输出两位，这正是"10 bit 摊到 5 个串行周期"的实现基础。
//   建模方式：上升沿/下降沿各用一个寄存器采样，再由 clk 电平二选一输出。
//   这是业界通用的 ODDR 行为建模写法，能正确反映"双沿输出"这一关键特性。
// =============================================================================
`timescale 1ns / 1ps

// -----------------------------------------------------------------------------
// EG_LOGIC_ODDR —— 双沿输出寄存器（DDR 输出）
// -----------------------------------------------------------------------------
module EG_LOGIC_ODDR (
    input  wire clk,
    input  wire rst,      // 高有效（与本项目 lane 模块的 rst_sync_s[1] 一致）
    input  wire d0,       // 上升沿采样
    input  wire d1,       // 下降沿采样
    output wire q
);

    reg q_pos;
    reg q_neg;

    // 原语上电即为确定的低电平（不是 x）。不写初值会让 x 在整个串化链路里
    // 传染，制造出"复位期间输出非 0"这类假故障。
    initial begin
        q_pos = 1'b0;
        q_neg = 1'b0;
    end

    always @(posedge clk) begin
        if (rst) q_pos <= 1'b0;
        else     q_pos <= d0;
    end

    always @(negedge clk) begin
        if (rst) q_neg <= 1'b0;
        else     q_neg <= d1;
    end

    // 上升沿之后输出 q_pos，下降沿之后输出 q_neg
    assign q = clk ? q_pos : q_neg;

endmodule

// -----------------------------------------------------------------------------
// EG_LOGIC_BUFG —— 全局时钟缓冲
// 只是把时钟扇出到全局网络，逻辑上是直通。
// 提供它是为了将来把 hdmi_pll / sdram_pll 也拉进仿真时不必再改文件。
// -----------------------------------------------------------------------------
module EG_LOGIC_BUFG (
    input  wire i,
    output wire o
);
    assign o = i;
endmodule

// -----------------------------------------------------------------------------
// EG_LOGIC_INV —— 反相器
// -----------------------------------------------------------------------------
module EG_LOGIC_INV (
    input  wire i,
    output wire o
);
    assign o = ~i;
endmodule
